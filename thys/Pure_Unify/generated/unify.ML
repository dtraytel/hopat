fun ff_assign alg env rbinder t u =
  bindW (get_eta_var rbinder (0 : IntInf.int) t)
    (fn (v, ta) =>
      bindW (liftM (occurs_terms env v [u]))
        (fn b =>
          (if b then raiseW ASSIGN
            else bindW (liftM (body_type env ta))
                   (fn t1 =>
                     bindW (liftM (fastype env rbinder u))
                       (fn t2 =>

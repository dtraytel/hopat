fun handleW m h =
  (case m of NONE => m | SOME (_, UOk _) => m
    | SOME (evs, UErr e) =>
      (case evs of [] => h e
        | _ :: _ => map_option (fn (evsa, a) => (evs @ evsa, a)) (h e)));

fun projenv cfg vname rbinder targs u env dpairs base ts head usb targ tail =
  let
    val (us, bary) = usb;
  in
    handleW
      (bindW
        (if cfg_trace_types cfg
          then test_unify_types (cfg_alg cfg) base bary env

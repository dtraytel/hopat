fun aconv_term (t1 $ u1) (t2 $ u2) = aconv_term t1 t2 andalso aconv_term u1 u2
  | aconv_term (Abs (uu, t1a, t1)) (Abs (uv, t2a, t2)) =
    aconv_term t1 t2 andalso ((t1a : typ) = t2a)
  | aconv_term (Const (v, va)) a2 = (((Const (v, va)) : term) = a2)
  | aconv_term (Free (v, va)) a2 = (((Free (v, va)) : term) = a2)
  | aconv_term (Var (v, va)) a2 = (((Var (v, va)) : term) = a2)
  | aconv_term (Bound v) a2 = (((Bound v) : term) = a2)
  | aconv_term (Abs (v, va, vb)) (Const (vc, vd)) =
    (((Abs (v, va, vb)) : term) = (Const (vc, vd)))
  | aconv_term (Abs (v, va, vb)) (Free (vc, vd)) =
    (((Abs (v, va, vb)) : term) = (Free (vc, vd)))
  | aconv_term (Abs (v, va, vb)) (Var (vc, vd)) =
    (((Abs (v, va, vb)) : term) = (Var (vc, vd)))
  | aconv_term (Abs (v, va, vb)) (Bound vc) =
    (((Abs (v, va, vb)) : term) = (Bound vc))
  | aconv_term (Abs (v, va, vb)) (vc $ vd) =
    (((Abs (v, va, vb)) : term) = (vc $ vd))
  | aconv_term a1 (Const (v, va)) = ((a1 : term) = (Const (v, va)))
  | aconv_term a1 (Free (v, va)) = ((a1 : term) = (Free (v, va)))
  | aconv_term a1 (Var (v, va)) = ((a1 : term) = (Var (v, va)))
  | aconv_term a1 (Bound v) = ((a1 : term) = (Bound v))
  | aconv_term (vc $ vd) (Abs (v, va, vb)) =
    (((vc $ vd) : term) = (Abs (v, va, vb)));

fun add_tpair rbinder t0 u0 tpairs =
  (if aconv_term t0 u0 then tpairs
    else let
           val t = rlist_abs rbinder t0;
           val u = rlist_abs rbinder u0;
         in
           (if list_ex (fn (ta, ua) => aconv_term t ta andalso aconv_term u ua)
                 tpairs
             then tpairs else (t, u) :: tpairs)
         end);

fun add_index loot loou jxT st =
  let
    val ((j, xT), (bnos, newbinder)) = (jxT, st);
  in
    (if member equal_integer loot j andalso member equal_integer loou j
      then (bnos, xT :: newbinder) else (j :: bnos, newbinder))
  end;

fun add_loose_bnos (Bound i) lev js =
  (if IntInf.< (i, lev) then js
    else insert equal_integer (IntInf.- (i, lev)) js)
  | add_loose_bnos (Abs (uu, uv, t)) lev js =
    add_loose_bnos t (IntInf.+ (lev, (1 : IntInf.int))) js
  | add_loose_bnos (f $ t) lev js =
    add_loose_bnos f lev (add_loose_bnos t lev js)
  | add_loose_bnos (Const (v, va)) ux js = js
  | add_loose_bnos (Free (v, va)) ux js = js
  | add_loose_bnos (Var (v, va)) ux js = js;

fun loose_bnos t = add_loose_bnos t (0 : IntInf.int) [];

fun clean_ffpair alg rbinder t u env tpairs =
  handleW
    let
      val loot = loose_bnos t;
      val loou = loose_bnos u;
      val (banned, rbin) =
        foldr (add_index loot loou)
          (zip (upto_list (size_list rbinder)) rbinder) ([], []);
    in
      bindW (clean_term banned env t)
        (fn (enva, ta) =>
          bindW (clean_term banned enva u)
            (fn (envb, ua) =>
              handleW
                (bindW (ff_assign alg envb rbin ta ua)
                  (fn env3 => returnW (env3, tpairs)))
                (fn e =>
                  (case e of PExn _ => raiseW e | CANTUNIFY => raiseW e
                    | ASSIGN =>
                      handleW
                        (bindW (ff_assign alg envb rbin ua ta)
                          (fn env3 => returnW (env3, tpairs)))
                        (fn ea =>
                          (case ea of PExn _ => raiseW ea
                            | CANTUNIFY => raiseW ea
                            | ASSIGN =>
                              returnW (envb, add_tpair rbin ta ua tpairs)
                            | CHANGE_FAIL => raiseW ea | Bind => raiseW ea))
                    | CHANGE_FAIL => raiseW e | Bind => raiseW e))))
    end
    (fn e =>
      (case e of PExn _ => raiseW e | CANTUNIFY => raiseW e | ASSIGN => raiseW e
        | CHANGE_FAIL => returnW (env, add_tpair rbinder t u tpairs)
        | Bind => raiseW e));

fun add_ffpair alg dp st =
  let
    val ((rbinder, (t0, u0)), (env, tpairs)) = (dp, st);
  in
    bindW (liftM (norm_term env t0))
      (fn t =>
        bindW (liftM (norm_term env u0))
          (fn u =>
            (case (head_of t, head_of u)
              of (Const (_, _), _) =>
                raiseW (PExn (Term_Error ("add_ffpair: Vars expected", [t, u])))
              | (Free (_, _), _) =>
                raiseW (PExn (Term_Error ("add_ffpair: Vars expected", [t, u])))
              | (Var (_, _), Const (_, _)) =>
                raiseW (PExn (Term_Error ("add_ffpair: Vars expected", [t, u])))
              | (Var (_, _), Free (_, _)) =>
                raiseW (PExn (Term_Error ("add_ffpair: Vars expected", [t, u])))
              | (Var (v, ta), Var (w, ua)) =>
                (if equal_proda equal_literal equal_integer v w
                  then (if ((ta : typ) = ua)
                         then returnW (env, add_tpair rbinder t u tpairs)
                         else raiseW
                                (PExn (Term_Error
("add_ffpair: Var name confusion", [t, u]))))
                  else (if indexname_less v w
                         then clean_ffpair alg rbinder u t env tpairs
                         else clean_ffpair alg rbinder t u env tpairs))
              | (Var (_, _), Bound _) =>
                raiseW (PExn (Term_Error ("add_ffpair: Vars expected", [t, u])))
              | (Var (_, _), Abs (_, _, _)) =>
                raiseW (PExn (Term_Error ("add_ffpair: Vars expected", [t, u])))
              | (Var (_, _), _ $ _) =>
                raiseW (PExn (Term_Error ("add_ffpair: Vars expected", [t, u])))
              | (Bound _, _) =>
                raiseW (PExn (Term_Error ("add_ffpair: Vars expected", [t, u])))
              | (Abs (_, _, _), _) =>
                raiseW (PExn (Term_Error ("add_ffpair: Vars expected", [t, u])))
              | (_ $ _, _) =>
                raiseW
                  (PExn (Term_Error ("add_ffpair: Vars expected", [t, u]))))))
  end;


fun mc cfg vname rbinder targs u env dpairs =
  let
    val uhead = fst (strip_comb u);
    val uargs = snd (strip_comb u);
  in
    bindW (liftM (fastype env rbinder uhead))
      (fn t0 =>
        bindW (liftM (body_type env t0))
          (fn base =>
            bindW (liftM (mapM (fastype env rbinder) targs))
              (fn ts =>
                (case uhead
                  of Const (_, _) =>
                    bindW (make_projs u targs ts targs)
                      (fn projs =>
                        matchfun cfg vname rbinder targs u env dpairs uhead
                          uargs base ts (rev projs))
                  | Free (_, _) =>
                    bindW (make_projs u targs ts targs)
                      (fn projs =>
                        matchfun cfg vname rbinder targs u env dpairs uhead
                          uargs base ts (rev projs))
                  | Var (w, _) =>
                    let

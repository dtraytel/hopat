fun rigid_bound lev banned t =
  (case strip_comb t
    of (Const (_, _), args) => list_ex (rigid_bound lev banned) args
    | (Free (_, _), args) => list_ex (rigid_bound lev banned) args
    | (Var (_, _), _) => false
    | (Bound i, args) =>
      member equal_integer banned (IntInf.- (i, lev)) orelse
        list_ex (rigid_bound lev banned) args
    | (Abs (_, _, u), args) =>
      null args andalso rigid_bound (IntInf.+ (lev, (1 : IntInf.int))) banned u
    | (_ $ _, args) => list_ex (rigid_bound lev banned) args);

fun change_bnos banned lev (Bound i) =
  (if IntInf.< (i, lev) then returnW (Bound i)
    else (if member equal_integer banned (IntInf.- (i, lev))
           then raiseW CHANGE_FAIL
           else returnW
                  (Bound
                    (IntInf.- (i, ilength
                                    (filter
                                      (fn j => IntInf.< (j, IntInf.- (i, lev)))
                                      banned))))))
  | change_bnos banned lev (Abs (a, ta, t)) =
    bindW (change_bnos banned (IntInf.+ (lev, (1 : IntInf.int))) t)
      (fn tb => returnW (Abs (a, ta, tb)))
  | change_bnos banned lev (t $ u) =
    bindW (change_bnos banned lev t)
      (fn ta => bindW (change_bnos banned lev u) (fn ua => returnW (ta $ ua)))
  | change_bnos banned lev (Const (v, va)) = returnW (Const (v, va))
  | change_bnos banned lev (Free (v, va)) = returnW (Free (v, va))
  | change_bnos banned lev (Var (v, va)) = returnW (Var (v, va));


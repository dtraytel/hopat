    | Abs (_, _, body) => occur body env v seen
    | f $ u =>
      bindM (occur u env v seen)
        (fn r =>
          (if fst r then return (true, snd r) else occur f env v (snd r))));

fun occurs_list env v seen [] = return (false, seen)
  | occurs_list env v seen (t :: ts) =
    bindM (occur t env v seen)
      (fn r =>
        (if fst r then return (true, snd r) else occurs_list env v (snd r) ts));

fun occurs_terms env v ts =
  bindM (occurs_list env v [] ts) (fn r => return (fst r));


      (fn e =>
        (case e of PExn _ => raiseW e | CANTUNIFY => returnW tail
          | ASSIGN => raiseW e | CHANGE_FAIL => raiseW e | Bind => raiseW e))
  end;

fun liftM m =
  (case m of NONE => NONE | SOME (Ok x) => SOME ([], UOk x)

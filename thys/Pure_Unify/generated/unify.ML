fun matchfun cfg vname rbinder targs u env dpairs uhead uargs base ts
  ((bvar, (t, targ)) :: projs) =
  bindW (liftM (strip_type env t))
    (fn usb =>
      bindW (matchfun cfg vname rbinder targs u env dpairs uhead uargs base ts
              projs)
        (projenv cfg vname rbinder targs u env dpairs base ts bvar usb targ))
  | matchfun cfg vname rbinder targs u env dpairs uhead uargs base ts [] =

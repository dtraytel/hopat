      (case uhead
        of Const (_, _) =>
          S_MapJoin (uhead, copyargs vname rbinder targs env dpairs uargs)
        | Free (_, _) =>
          S_MapJoin (uhead, copyargs vname rbinder targs env dpairs uargs)
        | Var (_, _) => S_Empty | Bound _ => S_Empty | Abs (_, _, _) => S_Empty
        | _ $ _ => S_Empty);


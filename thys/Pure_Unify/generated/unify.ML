fun bindW m f =
  (case m of NONE => NONE
    | SOME (evs, UOk x) =>
      (case evs of [] => f x
        | _ :: _ => map_option (fn (evsa, a) => (evs @ evsa, a)) (f x))
    | SOME (evs, UErr e) => SOME (evs, UErr e));

fun make_projs u targs0 (t :: ts) (targ :: targs) =
  bindW (make_projs u targs0 ts targs)
    (fn ps => returnW ((Bound (ilength ts), (t, targ)) :: ps))
  | make_projs u targs0 [] [] = returnW []
  | make_projs u targs0 [] (v :: va) =
    raiseW (PExn (Term_Error ("make_projs", u :: targs0)))
  | make_projs u targs0 (v :: va) [] =
    raiseW (PExn (Term_Error ("make_projs", u :: targs0)));

fun equal_list A_ [] (x21 :: x22) = false
  | equal_list A_ (x21 :: x22) [] = false
  | equal_list A_ (x21 :: x22) (y21 :: y22) =
    eq A_ x21 y21 andalso equal_list A_ x22 y22
  | equal_list A_ [] [] = true;

fun tvar_clash ixn sa s =
  raisea
    (Type_Error
      ("Type variable has two distinct sorts", [TVar (ixn, sa), TVar (ixn, s)],
        []));

fun type_lookup tye ixn s =
  (case Vartab.lookup tye ixn of NONE => return NONE
    | SOME (sa, t) =>
      (if equal_list equal_literal s sa then return (SOME t)
        else tvar_clash ixn s sa));

fun bindM m f =
  (case m of NONE => NONE | SOME (Ok a) => f a | SOME (Err e) => SOME (Err e));

fun body_type env t =
  (case t of Type (_, []) => return t | Type (_, [_]) => return t
    | Type (a, [_, u]) =>
      (if ((a : string) = "fun") then body_type env u else return t)
    | Type (_, _ :: _ :: _ :: _) => return t | TFree (_, _) => return t
    | TVar (v, s) =>
      bindM (type_lookup (Envir.type_env env) v s)
        (fn a => (case a of NONE => return t | SOME aa => body_type env aa)));

fun strip_comb_acc (f $ t) ts = strip_comb_acc f (t :: ts)
  | strip_comb_acc (Const (v, va)) ts = (Const (v, va), ts)
  | strip_comb_acc (Free (v, va)) ts = (Free (v, va), ts)
  | strip_comb_acc (Var (v, va)) ts = (Var (v, va), ts)
  | strip_comb_acc (Bound v) ts = (Bound v, ts)
  | strip_comb_acc (Abs (v, va, vb)) ts = (Abs (v, va, vb), ts);

fun strip_comb t = strip_comb_acc t [];

fun combound t n Zero_nat = t
  | combound t n (Suc k) =
    combound t (IntInf.+ (n, (1 : IntInf.int))) k $ Bound n;

fun binder_types env t =
  (case t of Type (_, []) => return [] | Type (_, [_]) => return []
    | Type (a, [t1, u]) =>
      (if ((a : string) = "fun")
        then bindM (binder_types env u) (fn us => return (t1 :: us))
        else return [])
    | Type (_, _ :: _ :: _ :: _) => return [] | TFree (_, _) => return []
    | TVar (v, s) =>
      bindM (type_lookup (Envir.type_env env) v s)
        (fn a =>
          (case a of NONE => return [] | SOME aa => binder_types env aa)));

fun strip_type env t =
  bindM (binder_types env t)
    (fn ts => bindM (body_type env t) (fn u => return (ts, u)));


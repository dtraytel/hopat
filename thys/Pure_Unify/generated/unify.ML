  | new_dpair alg rbinder (Bound v) (Free (va, vb)) env =
    returnW ((rbinder, (Bound v, Free (va, vb))), env)
  | new_dpair alg rbinder (Bound v) (Var (va, vb)) env =
    returnW ((rbinder, (Bound v, Var (va, vb))), env)
  | new_dpair alg rbinder (Bound v) (Bound va) env =
    returnW ((rbinder, (Bound v, Bound va)), env)
  | new_dpair alg rbinder (Bound v) (va $ vb) env =
    returnW ((rbinder, (Bound v, va $ vb)), env)
  | new_dpair alg rbinder (v $ va) (Const (vb, vc)) env =
    returnW ((rbinder, (v $ va, Const (vb, vc))), env)
  | new_dpair alg rbinder (v $ va) (Free (vb, vc)) env =
    returnW ((rbinder, (v $ va, Free (vb, vc))), env)
  | new_dpair alg rbinder (v $ va) (Var (vb, vc)) env =
    returnW ((rbinder, (v $ va, Var (vb, vc))), env)
  | new_dpair alg rbinder (v $ va) (Bound vb) env =
    returnW ((rbinder, (v $ va, Bound vb)), env)
  | new_dpair alg rbinder (v $ va) (vb $ vc) env =
    returnW ((rbinder, (v $ va, vb $ vc)), env);

fun head_norm_dpair alg env dp =
  let
    val (rbinder, (t, u)) = dp;
  in
    bindW (liftM (head_norm env t))
      (fn t1 =>
        bindW (liftM (eta_norm env rbinder t1))
          (fn t2 =>
            bindW (liftM (head_norm env u))
              (fn u1 =>
                bindW (liftM (eta_norm env rbinder u1))
                  (fn u2 => new_dpair alg rbinder t2 u2 env))))
  end;

fun is_Bound (Bound uu) = true
  | is_Bound (Const (v, va)) = false
  | is_Bound (Free (v, va)) = false
  | is_Bound (Var (v, va)) = false
  | is_Bound (Abs (v, va, vb)) = false
  | is_Bound (v $ va) = false;

fun pattern_occ v t =
  (case strip_comb t of (Const (_, _), _) => false | (Free (_, _), _) => false
    | (Var (w, _), ts) =>
      equal_proda equal_literal equal_integer w v andalso list_all is_Bound ts
    | (Bound _, _) => false | (Abs (_, _, _), _) => false
    | (_ $ _, _) => false);

fun head_of_in env t =
  (case t of Const (_, _) => return t | Free (_, _) => return t
    | Var (x, ta) =>
      bindM (lookup env x ta)
        (fn a => (case a of NONE => return t | SOME aa => head_of_in env aa))
    | Bound _ => return t | Abs (_, _, _) => return t
    | f $ _ => head_of_in env f);

fun nonrigid env v seen t =
  bindM (occurs_list env v seen [t])
    (fn (b, seena) => return ((if b then Nonrigid else NoOcc), seena));

fun equal_occ Nonrigid Rigid = false
  | equal_occ Rigid Nonrigid = false
  | equal_occ NoOcc Rigid = false
  | equal_occ Rigid NoOcc = false
  | equal_occ NoOcc Nonrigid = false
  | equal_occ Nonrigid NoOcc = false
  | equal_occ Rigid Rigid = true
  | equal_occ Nonrigid Nonrigid = true
  | equal_occ NoOcc NoOcc = true;

fun occomb oc seen (f $ t) =
  bindM (oc seen t)
    (fn r =>
      (if equal_occ (fst r) Rigid then return (Rigid, snd r)
        else bindM (occomb oc (snd r) f)
               (fn r2 =>
                 return
                   ((if equal_occ (fst r2) NoOcc then fst r else fst r2),
                     snd r2))))
  | occomb oc seen (Const (v, va)) = oc seen (Const (v, va))
  | occomb oc seen (Free (v, va)) = oc seen (Free (v, va))
  | occomb oc seen (Var (v, va)) = oc seen (Var (v, va))
  | occomb oc seen (Bound v) = oc seen (Bound v)
  | occomb oc seen (Abs (v, va, vb)) = oc seen (Abs (v, va, vb));

fun rocc t env v seen =
  (case t of Const (_, _) => return (NoOcc, seen)
    | Free (_, _) => return (NoOcc, seen)
    | Var (w, ta) =>
      (if member (equal_prod equal_literal equal_integer) seen w
        then return (NoOcc, seen)
        else (if equal_proda equal_literal equal_integer v w
               then return (Rigid, seen)
               else bindM (lookup env w ta)
                      (fn a =>
                        (case a of NONE => return (NoOcc, w :: seen)
                          | SOME u => rocc u env v (w :: seen)))))
    | Bound _ => return (NoOcc, seen) | Abs (_, _, body) => rocc body env v seen
    | f $ _ =>
      bindM (head_of_in env f)
        (fn a =>
          (case a
            of Const (_, _) =>
              occomb (fn seena => fn ta => rocc ta env v seena) seen t
            | Free (_, _) =>
              occomb (fn seena => fn ta => rocc ta env v seena) seen t
            | Var (w, _) =>
              (if equal_proda equal_literal equal_integer v w andalso
                    pattern_occ v t
                then return (Rigid, seen) else nonrigid env v seen t)
            | Bound _ =>
              occomb (fn seena => fn ta => rocc ta env v seena) seen t
            | Abs (_, _, _) => nonrigid env v seen t
            | _ $ _ =>
              occomb (fn seena => fn ta => rocc ta env v seena) seen t)));

fun rigid_occurs_term env v t =
  bindM (rocc t env v []) (fn r => return (fst r));

fun assignment alg rbinder t u env =
  bindW (get_eta_var rbinder (0 : IntInf.int) t)
    (fn (v, ta) =>
      bindW (liftM (rigid_occurs_term env v u))
        (fn a =>
          (case a
            of NoOcc =>
              bindW (liftM (body_type env ta))
                (fn t1 =>
                  bindW (liftM (fastype env rbinder u))
                    (fn t2 =>
                      bindW (cunify_types alg t1 t2 env)
                        (fn enva =>
                          liftM (update (v, ta) (rlist_abs rbinder u) enva))))
            | Nonrigid => raiseW ASSIGN | Rigid => raiseW CANTUNIFY)));

fun simrands f rbinder u0 (f1 $ t) (g1 $ u) st =
  bindW (simrands f rbinder u0 f1 g1 st) (f (rbinder, (t, u)))
  | simrands f rbinder u0 (t1 $ t2) (Const (v, va)) st =
    raiseW (PExn (Term_Error ("SIMPL: operands mismatch", [t1 $ t2, u0])))
  | simrands f rbinder u0 (t1 $ t2) (Free (v, va)) st =
    raiseW (PExn (Term_Error ("SIMPL: operands mismatch", [t1 $ t2, u0])))
  | simrands f rbinder u0 (t1 $ t2) (Var (v, va)) st =
    raiseW (PExn (Term_Error ("SIMPL: operands mismatch", [t1 $ t2, u0])))
  | simrands f rbinder u0 (t1 $ t2) (Bound v) st =
    raiseW (PExn (Term_Error ("SIMPL: operands mismatch", [t1 $ t2, u0])))
  | simrands f rbinder u0 (t1 $ t2) (Abs (v, va, vb)) st =
    raiseW (PExn (Term_Error ("SIMPL: operands mismatch", [t1 $ t2, u0])))
  | simrands f rbinder u0 (Const (v, va)) (u1 $ u2) st =
    raiseW
      (PExn (Term_Error ("SIMPL: operands mismatch", [Const (v, va), u1 $ u2])))
  | simrands f rbinder u0 (Free (v, va)) (u1 $ u2) st =
    raiseW
      (PExn (Term_Error ("SIMPL: operands mismatch", [Free (v, va), u1 $ u2])))
  | simrands f rbinder u0 (Var (v, va)) (u1 $ u2) st =
    raiseW
      (PExn (Term_Error ("SIMPL: operands mismatch", [Var (v, va), u1 $ u2])))
  | simrands f rbinder u0 (Bound v) (u1 $ u2) st =
    raiseW (PExn (Term_Error ("SIMPL: operands mismatch", [Bound v, u1 $ u2])))
  | simrands f rbinder u0 (Abs (v, va, vb)) (u1 $ u2) st =
    raiseW
      (PExn (Term_Error
              ("SIMPL: operands mismatch", [Abs (v, va, vb), u1 $ u2])))
  | simrands f rbinder u0 (Const (v, va)) (Const (vb, vc)) st = returnW st
  | simrands f rbinder u0 (Const (v, va)) (Free (vb, vc)) st = returnW st
  | simrands f rbinder u0 (Const (v, va)) (Var (vb, vc)) st = returnW st
  | simrands f rbinder u0 (Const (v, va)) (Bound vb) st = returnW st
  | simrands f rbinder u0 (Const (v, va)) (Abs (vb, vc, vd)) st = returnW st
  | simrands f rbinder u0 (Free (v, va)) (Const (vb, vc)) st = returnW st
  | simrands f rbinder u0 (Free (v, va)) (Free (vb, vc)) st = returnW st
  | simrands f rbinder u0 (Free (v, va)) (Var (vb, vc)) st = returnW st
  | simrands f rbinder u0 (Free (v, va)) (Bound vb) st = returnW st
  | simrands f rbinder u0 (Free (v, va)) (Abs (vb, vc, vd)) st = returnW st
  | simrands f rbinder u0 (Var (v, va)) (Const (vb, vc)) st = returnW st
  | simrands f rbinder u0 (Var (v, va)) (Free (vb, vc)) st = returnW st
  | simrands f rbinder u0 (Var (v, va)) (Var (vb, vc)) st = returnW st
  | simrands f rbinder u0 (Var (v, va)) (Bound vb) st = returnW st
  | simrands f rbinder u0 (Var (v, va)) (Abs (vb, vc, vd)) st = returnW st
  | simrands f rbinder u0 (Bound v) (Const (va, vb)) st = returnW st
  | simrands f rbinder u0 (Bound v) (Free (va, vb)) st = returnW st
  | simrands f rbinder u0 (Bound v) (Var (va, vb)) st = returnW st
  | simrands f rbinder u0 (Bound v) (Bound va) st = returnW st
  | simrands f rbinder u0 (Bound v) (Abs (va, vb, vc)) st = returnW st
  | simrands f rbinder u0 (Abs (v, va, vb)) (Const (vc, vd)) st = returnW st
  | simrands f rbinder u0 (Abs (v, va, vb)) (Free (vc, vd)) st = returnW st
  | simrands f rbinder u0 (Abs (v, va, vb)) (Var (vc, vd)) st = returnW st
  | simrands f rbinder u0 (Abs (v, va, vb)) (Bound vc) st = returnW st
  | simrands f rbinder u0 (Abs (v, va, vb)) (Abs (vc, vd, ve)) st = returnW st;

fun sIMPL0 alg dp0 st =
  let
    val (env, (ffs, frs)) = st;
  in
    bindW (head_norm_dpair alg env dp0)
      (fn (dp, enva) =>
        let
          val (rbinder, (t, u)) = dp;
        in
          (case (head_of t, head_of u)
            of (Const (literal, ptyp), Const (b, ua)) =>
              (if ((literal : string) = b)
                then bindW (cunify_types alg ptyp ua enva)
                       (fn envb =>
                         simrands (sIMPL0 alg) rbinder u t u (envb, (ffs, frs)))
                else raiseW CANTUNIFY)
            | (Const (_, _), Free (_, _)) => raiseW CANTUNIFY
            | (Const (_, _), Var (_, _)) =>
              handleW
                (bindW (assignment alg rbinder u t enva)
                  (fn envb => returnW (envb, (ffs, frs))))
                (fn e =>
                  (case e of PExn _ => raiseW e | CANTUNIFY => raiseW e
                    | ASSIGN => returnW (enva, (ffs, (rbinder, (u, t)) :: frs))
                    | CHANGE_FAIL => raiseW e | Bind => raiseW e))
            | (Const (_, _), Bound _) => raiseW CANTUNIFY
            | (Const (_, _), Abs (_, _, _)) => raiseW CANTUNIFY
            | (Const (_, _), _ $ _) => raiseW CANTUNIFY
            | (Free (_, _), Const (_, _)) => raiseW CANTUNIFY
            | (Free (literal, ptyp), Free (b, ua)) =>
              (if ((literal : string) = b)
                then bindW (cunify_types alg ptyp ua enva)
                       (fn envb =>
                         simrands (sIMPL0 alg) rbinder u t u (envb, (ffs, frs)))
                else raiseW CANTUNIFY)
            | (Free (_, _), Var (_, _)) =>
              handleW
                (bindW (assignment alg rbinder u t enva)
                  (fn envb => returnW (envb, (ffs, frs))))
                (fn e =>
                  (case e of PExn _ => raiseW e | CANTUNIFY => raiseW e
                    | ASSIGN => returnW (enva, (ffs, (rbinder, (u, t)) :: frs))
                    | CHANGE_FAIL => raiseW e | Bind => raiseW e))
            | (Free (_, _), Bound _) => raiseW CANTUNIFY
            | (Free (_, _), Abs (_, _, _)) => raiseW CANTUNIFY
            | (Free (_, _), _ $ _) => raiseW CANTUNIFY
            | (Var (_, _), Const (_, _)) =>
              handleW
                (bindW (assignment alg rbinder t u enva)
                  (fn envb => returnW (envb, (ffs, frs))))
                (fn e =>
                  (case e of PExn _ => raiseW e | CANTUNIFY => raiseW e
                    | ASSIGN => returnW (enva, (ffs, dp :: frs))
                    | CHANGE_FAIL => raiseW e | Bind => raiseW e))
            | (Var (_, _), Free (_, _)) =>
              handleW
                (bindW (assignment alg rbinder t u enva)
                  (fn envb => returnW (envb, (ffs, frs))))
                (fn e =>
                  (case e of PExn _ => raiseW e | CANTUNIFY => raiseW e
                    | ASSIGN => returnW (enva, (ffs, dp :: frs))
                    | CHANGE_FAIL => raiseW e | Bind => raiseW e))
            | (Var (_, ta), Var (_, ua)) =>
              bindW (liftM (body_type enva ta))
                (fn tb =>
                  bindW (liftM (body_type enva ua))
                    (fn ub =>
                      bindW (cunify_types alg tb ub enva)
                        (fn envb => returnW (envb, (dp :: ffs, frs)))))
            | (Var (_, _), Bound _) =>
              handleW
                (bindW (assignment alg rbinder t u enva)
                  (fn envb => returnW (envb, (ffs, frs))))
                (fn e =>
                  (case e of PExn _ => raiseW e | CANTUNIFY => raiseW e
                    | ASSIGN => returnW (enva, (ffs, dp :: frs))
                    | CHANGE_FAIL => raiseW e | Bind => raiseW e))
            | (Var (_, _), Abs (_, _, _)) =>
              handleW
                (bindW (assignment alg rbinder t u enva)
                  (fn envb => returnW (envb, (ffs, frs))))
                (fn e =>
                  (case e of PExn _ => raiseW e | CANTUNIFY => raiseW e
                    | ASSIGN => returnW (enva, (ffs, dp :: frs))
                    | CHANGE_FAIL => raiseW e | Bind => raiseW e))
            | (Var (_, _), _ $ _) =>
              handleW
                (bindW (assignment alg rbinder t u enva)
                  (fn envb => returnW (envb, (ffs, frs))))
                (fn e =>
                  (case e of PExn _ => raiseW e | CANTUNIFY => raiseW e
                    | ASSIGN => returnW (enva, (ffs, dp :: frs))
                    | CHANGE_FAIL => raiseW e | Bind => raiseW e))
            | (Bound _, Const (_, _)) => raiseW CANTUNIFY
            | (Bound _, Free (_, _)) => raiseW CANTUNIFY
            | (Bound _, Var (_, _)) =>
              handleW
                (bindW (assignment alg rbinder u t enva)
                  (fn envb => returnW (envb, (ffs, frs))))
                (fn e =>
                  (case e of PExn _ => raiseW e | CANTUNIFY => raiseW e
                    | ASSIGN => returnW (enva, (ffs, (rbinder, (u, t)) :: frs))
                    | CHANGE_FAIL => raiseW e | Bind => raiseW e))
            | (Bound integer, Bound j) =>
              (if ((integer : IntInf.int) = j)
                then simrands (sIMPL0 alg) rbinder u t u (enva, (ffs, frs))
                else raiseW CANTUNIFY)
            | (Bound _, Abs (_, _, _)) => raiseW CANTUNIFY
            | (Bound _, _ $ _) => raiseW CANTUNIFY
            | (Abs (_, _, _), Const (_, _)) => raiseW CANTUNIFY
            | (Abs (_, _, _), Free (_, _)) => raiseW CANTUNIFY
            | (Abs (_, _, _), Var (_, _)) =>
              handleW
                (bindW (assignment alg rbinder u t enva)
                  (fn envb => returnW (envb, (ffs, frs))))
                (fn e =>
                  (case e of PExn _ => raiseW e | CANTUNIFY => raiseW e
                    | ASSIGN => returnW (enva, (ffs, (rbinder, (u, t)) :: frs))
                    | CHANGE_FAIL => raiseW e | Bind => raiseW e))
            | (Abs (_, _, _), Bound _) => raiseW CANTUNIFY
            | (Abs (_, _, _), Abs (_, _, _)) => raiseW CANTUNIFY
            | (Abs (_, _, _), _ $ _) => raiseW CANTUNIFY
            | (_ $ _, Const (_, _)) => raiseW CANTUNIFY
            | (_ $ _, Free (_, _)) => raiseW CANTUNIFY
            | (_ $ _, Var (_, _)) =>
              handleW
                (bindW (assignment alg rbinder u t enva)
                  (fn envb => returnW (envb, (ffs, frs))))
                (fn e =>
                  (case e of PExn _ => raiseW e | CANTUNIFY => raiseW e
                    | ASSIGN => returnW (enva, (ffs, (rbinder, (u, t)) :: frs))
                    | CHANGE_FAIL => raiseW e | Bind => raiseW e))
            | (_ $ _, Bound _) => raiseW CANTUNIFY
            | (_ $ _, Abs (_, _, _)) => raiseW CANTUNIFY
            | (_ $ _, _ $ _) => raiseW CANTUNIFY)
        end)
  end;

fun simpl alg env dpairs =
  bindW (foldrW (sIMPL0 alg) dpairs (env, ([], [])))
    (fn st =>
      let
        val (enva, (ffs, frs)) = st;
        val dps = frs @ ffs;
      in
        bindW (liftM
                (existsM
                  (fn (_, (t, u)) =>
                    bindM (changed enva t)
                      (fn b => (if b then return true else changed enva u)))
                  dps))
          (fn b => (if b then simpl alg enva dps else returnW st))
      end);

fun match1_projs cfg vname env dpairs base ts ((bvar, (t, targ)) :: projs) tail
  = bindW (liftM (strip_type env t))
      (fn usb =>
        bindW (match1_projs cfg vname env dpairs base ts projs tail)
          (fn tl =>
            let
              val (us, bary) = usb;
            in
              handleW
                (bindW
                  (if cfg_trace_types cfg
                    then test_unify_types (cfg_alg cfg) base bary env
                    else cunify_types (cfg_alg cfg) base bary env)
                  (fn enva =>
                    let
                      val (envb, args) = make_args vname ts enva us;
                    in
                      returnW
                        (S_Append
                          (S_Single (El_C (list_comb bvar args, envb, dpairs)),
                            tl))
                    end))
                (fn e =>
                  (case e of PExn _ => raiseW e | CANTUNIFY => returnW tl
                    | ASSIGN => raiseW e | CHANGE_FAIL => raiseW e
                    | Bind => raiseW e))
            end))
  | match1_projs cfg vname env dpairs base ts [] tail = returnW tail;

fun match1 cfg vname rbinder targs u env dpairs =
  let
    val uhead = fst (strip_comb u);
  in
    bindW (liftM (fastype env rbinder uhead))
      (fn t0 =>
        bindW (liftM (body_type env t0))
          (fn base =>
            bindW (liftM (mapM (fastype env rbinder) targs))
              (fn ts =>
                bindW (make_projs u targs ts targs)
                  (fn projs =>
                    bindW (case uhead
                            of Const (_, _) =>
                              bindW (liftM (binder_types env t0))
                                (fn us =>
                                  let
                                    val (enva, args) =
                                      make_args vname ts env us;
                                  in
                                    returnW
                                      (S_Single
(El_C (list_comb uhead args, enva, dpairs)))
                                  end)
                            | Free (_, _) =>
                              bindW (liftM (binder_types env t0))
                                (fn us =>
                                  let
                                    val (enva, args) =
                                      make_args vname ts env us;
                                  in
                                    returnW
                                      (S_Single
(El_C (list_comb uhead args, enva, dpairs)))
                                  end)
                            | Var (_, _) => returnW S_Empty
                            | Bound _ => returnW S_Empty
                            | Abs (_, _, _) => returnW S_Empty
                            | _ $ _ => returnW S_Empty)
                      (match1_projs cfg vname env dpairs base ts
                        (rev projs))))))
  end;

fun match cfg env dp dpairs =
  let
    val (rbinder, (t, u)) = dp;
  in
    (case strip_comb t of (Const (_, _), _) => raiseW Bind
      | (Free (_, _), _) => raiseW Bind
      | (Var (v, ta), targs) =>
        bindW (liftM (binder_types env ta))
          (fn ts =>
            bindW (liftM
                    (occurs_terms env v
                      (u :: targs @
                              maps (fn (_, (tb, ua)) => [tb, ua]) dpairs)))
              (fn occ =>
                bindW (if occ
                        then match1 cfg (fst v) rbinder targs u env
                               (dp :: dpairs)
                        else mc cfg (fst v) rbinder targs u env dpairs)
                  (fn s => returnW (S_MapNewDset ((v, ta), ts, s)))))
      | (Bound _, _) => raiseW Bind | (Abs (_, _, _), _) => raiseW Bind
      | (_ $ _, _) => raiseW Bind)
  end;

fun pull cfg s =
  (case s of S_Empty => returnW NONE | S_Single x => returnW (SOME (x, S_Empty))
    | S_AddUnify (tdepth, env, dpairs, reseq) =>
      handleW
        (bindW
          (whenW
            (IntInf.< (cfg_trace_bound cfg, tdepth) andalso cfg_trace_simp cfg)
            (emit (Ev_Dpairs ("Enter SIMPL", env, dpairs))))
          (fn _ =>
            bindW (simpl (cfg_alg cfg) env dpairs)
              (fn (enva, (ffs, frs)) =>
                (case frs
                  of [] =>
                    bindW (foldrW (add_ffpair (cfg_alg cfg)) ffs (enva, []))
                      (fn r => returnW (SOME (El_R (fst r, snd r), reseq)))
                  | dp :: frigid =>
                    (if IntInf.< (cfg_search_bound cfg, tdepth)
                      then bindW (emit Ev_Bound_Exceeded)
                             (fn _ => pull cfg reseq)
                      else bindW (whenW (IntInf.< (cfg_trace_bound cfg, tdepth))
                                   (emit (Ev_Dpairs
   ("Enter MATCH", enva, frs @ ffs))))
                             (fn _ =>
                               bindW (match cfg enva dp (frigid @ ffs))
                                 (fn ms =>
                                   pull cfg
                                     (S_ItRight
                                       (IntInf.+ (tdepth, (1 : IntInf.int)), ms,
 reseq)))))))))
        (fn e =>
          (case e of PExn _ => raiseW e
            | CANTUNIFY =>
              bindW (whenW (IntInf.< (cfg_trace_bound cfg, tdepth))
                      (emit Ev_Failure_Node))
                (fn _ => pull cfg reseq)
            | ASSIGN => raiseW e | CHANGE_FAIL => raiseW e | Bind => raiseW e))
    | S_ItRight (tdepth, xq, yq) =>
      bindW (pull cfg xq)
        (fn a =>
          (case a of NONE => pull cfg yq | SOME (El_R (_, _), _) => pull_fail
            | SOME (El_E (env, dpairs), xqa) =>
              pull cfg
                (S_AddUnify (tdepth, env, dpairs, S_ItRight (tdepth, xqa, yq)))
            | SOME (El_C (_, _, _), _) => pull_fail
            | SOME (El_D (_, _, _), _) => pull_fail))
    | S_MapNewDset (vT, ts, xq) =>
      bindW (pull cfg xq)
        (fn a =>
          (case a of NONE => returnW NONE | SOME (El_R (_, _), _) => pull_fail
            | SOME (El_E (_, _), _) => pull_fail
            | SOME (El_C (u, env, dpairs), xqa) =>
              bindW (new_dset vT ts u env dpairs)
                (fn y => returnW (SOME (y, S_MapNewDset (vT, ts, xqa))))
            | SOME (El_D (_, _, _), _) => pull_fail))
    | S_MapAbs (a, t, xq) =>
      bindW (pull cfg xq)
        (fn b =>
          (case b of NONE => returnW NONE | SOME (El_R (_, _), _) => pull_fail
            | SOME (El_E (_, _), _) => pull_fail
            | SOME (El_C (body, env, dpairs), xqa) =>
              returnW
                (SOME (El_C (Abs (a, t, body), env, dpairs),
                        S_MapAbs (a, t, xqa)))
            | SOME (El_D (_, _, _), _) => pull_fail))
    | S_Proj (vname, env, ts, us, targs, rbinder, u, dpairs, head, targ, tail)
      => handleW
           let
             val (enva, args) = make_args vname ts env us;
             val dp =
               (rbinder,
                 (list_comb targ
                    (map (fn arg => list_comb (head_of arg) targs) args),
                   u));
           in
             bindW (simpl (cfg_alg cfg) enva (dp :: dpairs))
               (fn (env2, (frigid, fflex)) =>
                 returnW
                   (SOME (El_C (list_comb head args, env2, frigid @ fflex),
                           tail)))
           end
           (fn e =>
             (case e of PExn _ => raiseW e | CANTUNIFY => pull cfg tail
               | ASSIGN => raiseW e | CHANGE_FAIL => raiseW e
               | Bind => raiseW e))
    | S_MapJoin (uhead, xq) =>
      bindW (pull cfg xq)
        (fn a =>
          (case a of NONE => returnW NONE | SOME (El_R (_, _), _) => pull_fail
            | SOME (El_E (_, _), _) => pull_fail
            | SOME (El_C (_, _, _), _) => pull_fail
            | SOME (El_D (uargs, env, dpairs), xqa) =>
              returnW
                (SOME (El_C (list_comb uhead uargs, env, dpairs),
                        S_MapJoin (uhead, xqa)))))
    | S_Maps (vname, rbinder, targs, uarg, xq) =>
      bindW (pull cfg xq)
        (fn a =>
          (case a of NONE => returnW NONE | SOME (El_R (_, _), _) => pull_fail
            | SOME (El_E (_, _), _) => pull_fail
            | SOME (El_C (_, _, _), _) => pull_fail
            | SOME (El_D (uargs, env, dpairs), xqa) =>
              bindW (copycons cfg vname rbinder targs uarg uargs env dpairs)
                (fn cs =>
                  pull cfg
                    (S_Append
                      (cs, S_Maps (vname, rbinder, targs, uarg, xqa))))))
    | S_Append (xq, yq) =>
      bindW (pull cfg xq)
        (fn a =>
          (case a of NONE => pull cfg yq
            | SOME (x, xqa) => returnW (SOME (x, S_Append (xqa, yq)))))
    | S_MapCons (uargs, xq) =>
      bindW (pull cfg xq)
        (fn a =>
          (case a of NONE => returnW NONE | SOME (El_R (_, _), _) => pull_fail
            | SOME (El_E (_, _), _) => pull_fail
            | SOME (El_C (uarg, env, dpairs), xqa) =>
              returnW
                (SOME (El_D (uarg :: uargs, env, dpairs),
                        S_MapCons (uargs, xqa)))
            | SOME (El_D (_, _, _), _) => pull_fail)));

fun type_abs env ta t =
  bindM (binder_types env ta) (fn ts => return (types_abs ts t));

fun hounifiers binders env tus =
  S_AddUnify
    ((1 : IntInf.int), env, map (fn (t, u) => (binders, (t, u))) tus, S_Empty);

fun strip_abs_body (Abs (uu, uv, t)) = strip_abs_body t
  | strip_abs_body (Const (v, va)) = Const (v, va)
  | strip_abs_body (Free (v, va)) = Free (v, va)
  | strip_abs_body (Var (v, va)) = Var (v, va)
  | strip_abs_body (Bound v) = Bound v
  | strip_abs_body (v $ va) = v $ va;

fun var_head_of env t =
  bindW (liftM (norm_term env t))
    (fn ta =>
      (case head_of (strip_abs_body ta) of Const (_, _) => raiseW CANTUNIFY
        | Free (_, _) => raiseW CANTUNIFY | Var (v, tb) => returnW (v, tb)
        | Bound _ => raiseW CANTUNIFY | Abs (_, _, _) => raiseW CANTUNIFY
        | _ $ _ => raiseW CANTUNIFY));

fun smash_flexflex1 tu env =
  let
    val (t, u) = tu;
  in
    bindW (var_head_of env t)
      (fn (v, ta) =>
        bindW (var_head_of env u)
          (fn (w, ua) =>
            bindW (liftM (body_type env ta))
              (fn b =>
                let
                  val (enva, var) = genvar (fst v) env b;
                in
                  bindW (liftM (type_abs enva ua var))
                    (fn tU =>
                      bindW (liftM (vupdate (w, ua) tU enva))
                        (fn envaa =>
                          (if equal_proda equal_literal equal_integer v
                                w andalso
                                ((ta : typ) = ua)
                            then returnW envaa
                            else bindW (liftM (type_abs enva ta var))
                                   (fn tT =>
                                     liftM (vupdate (v, ta) tT envaa)))))
                end)))
  end;

fun smash_flexflex et = let
                          val (env, tpairs) = et;
                        in
                          foldrW smash_flexflex1 tpairs env
                        end;


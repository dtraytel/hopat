val funerr : string = "fastype: expected function type";

fun env_fastype env ts (f $ u) =
  bindM (env_fastype env ts f)
    (fn t =>
      bindM (devar (Envir.type_env env) t)
        (fn a =>
          (case a of Type (_, []) => raisea (Term_Error (funerr, [f $ u]))
            | Type (_, [_]) => raisea (Term_Error (funerr, [f $ u]))
            | Type (aa, [_, ua]) =>
              (if ((aa : string) = "fun") then return ua
                else raisea (Term_Error (funerr, [f $ u])))
            | Type (_, _ :: _ :: _ :: _) =>
              raisea (Term_Error (funerr, [f $ u]))
            | TFree (_, _) => raisea (Term_Error (funerr, [f $ u]))
            | TVar (_, _) => raisea (Term_Error (funerr, [f $ u])))))
  | env_fastype env ts (Const (uu, t)) = return t
  | env_fastype env ts (Free (uv, t)) = return t
  | env_fastype env ts (Bound i) =
    handlea (nth ts i)
      (fn e =>
        (case e of Unif _ => raisea e | Pattern => raisea e | Match => raisea e
          | TUnify => raisea e | Type_Match => raisea e
          | Class_Error _ => raisea e | Type_Error (_, _, _) => raisea e
          | Term_Error (_, _) => raisea e | Failure _ => raisea e
          | Subscript => raisea (Term_Error ("fastype: Bound", [Bound i]))
          | Unequal_Lengths => raisea e | Dup _ => raisea e))
  | env_fastype env ts (Var (uw, t)) = return t
  | env_fastype env ts (Abs (ux, t, u)) =
    bindM (env_fastype env (t :: ts) u)
      (fn ua => return (Type ("fun", [t, ua])));

fun fastype env ts t = env_fastype env (map snd ts) t;


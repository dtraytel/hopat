fun head_norm env t =
  (case t of Const (_, _) => return t | Free (_, _) => return t
    | Var (xi, ta) =>
      bindM (lookup env xi ta)
        (fn a => (case a of NONE => return t | SOME aa => head_norm env aa))
    | Bound _ => return t
    | Abs (a, ta, body) =>
      bindM (head_norm env body) (fn bodya => return (Abs (a, ta, bodya)))
    | f $ u =>
      (case f
        of Const (_, _) =>
          bindM (head_norm env f)
            (fn nf =>
              (case nf of Const (_, _) => return (nf $ u)
                | Free (_, _) => return (nf $ u) | Var (_, _) => return (nf $ u)
                | Bound _ => return (nf $ u)
                | Abs (_, _, body) => head_norm env (subst_bound u body)
                | _ $ _ => return (nf $ u)))
        | Free (_, _) =>
          bindM (head_norm env f)
            (fn nf =>
              (case nf of Const (_, _) => return (nf $ u)
                | Free (_, _) => return (nf $ u) | Var (_, _) => return (nf $ u)
                | Bound _ => return (nf $ u)
                | Abs (_, _, body) => head_norm env (subst_bound u body)
                | _ $ _ => return (nf $ u)))
        | Var (_, _) =>
          bindM (head_norm env f)
            (fn nf =>
              (case nf of Const (_, _) => return (nf $ u)
                | Free (_, _) => return (nf $ u) | Var (_, _) => return (nf $ u)
                | Bound _ => return (nf $ u)
                | Abs (_, _, body) => head_norm env (subst_bound u body)
                | _ $ _ => return (nf $ u)))
        | Bound _ =>
          bindM (head_norm env f)
            (fn nf =>
              (case nf of Const (_, _) => return (nf $ u)
                | Free (_, _) => return (nf $ u) | Var (_, _) => return (nf $ u)
                | Bound _ => return (nf $ u)
                | Abs (_, _, body) => head_norm env (subst_bound u body)
                | _ $ _ => return (nf $ u)))
        | Abs (_, _, body) => head_norm env (subst_bound u body)
        | _ $ _ =>
          bindM (head_norm env f)
            (fn nf =>
              (case nf of Const (_, _) => return (nf $ u)
                | Free (_, _) => return (nf $ u) | Var (_, _) => return (nf $ u)
                | Bound _ => return (nf $ u)
                | Abs (_, _, body) => head_norm env (subst_bound u body)
                | _ $ _ => return (nf $ u)))));


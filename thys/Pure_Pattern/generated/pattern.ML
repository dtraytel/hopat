  | strip_comb_acc (Free (v, va)) ts = (Free (v, va), ts)
  | strip_comb_acc (Var (v, va)) ts = (Var (v, va), ts)
  | strip_comb_acc (Bound v) ts = (Bound v, ts)
  | strip_comb_acc (Abs (v, va, vb)) ts = (Abs (v, va, vb), ts);

fun strip_comb t = strip_comb_acc t [];

fun mapAccM f [] s = return ([], s)
  | mapAccM f (x :: xs) s =
    bindM (f x s)
      (fn (y, s1) =>
        bindM (mapAccM f xs s1) (fn (ys, s2) => return (y :: ys, s2)));

fun list_comb t ts = foldl (fn a => fn b => a $ b) t ts;

fun mk_hnf binders is g js = mkabs binders is (app g js);

fun trans is d i =
  (if IntInf.< (i, d) then return i
    else bindM (idx is (IntInf.- (i, d))) (fn j => return (IntInf.+ (j, d))));

fun is_Var (Var (uu, uv)) = true
  | is_Var (Const (v, va)) = false
  | is_Var (Free (v, va)) = false
  | is_Var (Bound v) = false
  | is_Var (Abs (v, va, vb)) = false
  | is_Var (v $ va) = false;

fun is_Abs (Abs (uu, uv, uw)) = true
  | is_Abs (Const (v, va)) = false
  | is_Abs (Free (v, va)) = false
  | is_Abs (Var (v, va)) = false
  | is_Abs (Bound v) = false
  | is_Abs (v $ va) = false;

fun pr xs s env d binders =
  bindM (head_norm env s)
    (fn sa =>
      (if is_Abs sa
        then (case sa of Const (_, _) => raisea (Failure "pr")
               | Free (_, _) => raisea (Failure "pr")
               | Var (_, _) => raisea (Failure "pr")
               | Bound _ => raisea (Failure "pr")
               | Abs (a, t, ta) =>
                 bindM (pr xs ta env (IntInf.+ (d, (1 : IntInf.int)))
                         ((a, t) :: binders))
                   (fn (taa, enva) => return (Abs (a, t, taa), enva))
               | _ $ _ => raisea (Failure "pr"))
        else let
               val (h, ts) = strip_comb sa;
             in
               (if is_Var h
                 then (case h of Const (_, _) => raisea (Failure "pr")
                        | Free (_, _) => raisea (Failure "pr")
                        | Var (f, fty) =>
                          bindM (ints_ofa env ts)
                            (fn js =>
                              bindM (mapM (try_trans xs d) js)
                                (fn jsa =>
                                  let
                                    val ks = mk_proj_list jsa;
                                    val ls = map_filter id jsa;
                                  in
                                    bindM (type_of_G env fty (ilength js) ks)
                                      (fn hty =>
let
  val (enva, ha) = genvar (fst f) env hty;
in
  bindM (mk_hnf binders js ha ks)
    (fn t =>
      bindM (update (f, fty) t enva) (fn envb => return (app ha ls, envb)))
end)
                                  end))
                        | Bound _ => raisea (Failure "pr")
                        | Abs (_, _, _) => raisea (Failure "pr")
                        | _ $ _ => raisea (Failure "pr"))
                 else (if is_Abs h then raisea Pattern
                        else bindM (case h of Const (_, _) => return h
                                     | Free (_, _) => return h
                                     | Var (_, _) => return h
                                     | Bound i =>
                                       bindM (trans xs d i)
 (fn j => return (Bound j))
                                     | Abs (_, _, _) => return h
                                     | _ $ _ => return h)
                               (fn ha =>
                                 bindM (mapAccM
 (fn sb => fn enva => pr xs sb enva d binders) ts env)
                                   (fn (tsa, enva) =>
                                     return (list_comb ha tsa, enva)))))
             end));

fun mapbnd f d (Bound i) =
  (if IntInf.< (i, d) then return (Bound i)
    else bindM (f (IntInf.- (i, d))) (fn j => return (Bound (IntInf.+ (j, d)))))
  | mapbnd f d (Abs (s, ta, t)) =
    bindM (mapbnd f (IntInf.+ (d, (1 : IntInf.int))) t)
      (fn tb => return (Abs (s, ta, tb)))
  | mapbnd f d (u1 $ u2) =
    bindM (mapbnd f d u1)
      (fn u1a => bindM (mapbnd f d u2) (fn u2a => return (u1a $ u2a)))
  | mapbnd f d (Const (v, va)) = return (Const (v, va))
  | mapbnd f d (Free (v, va)) = return (Free (v, va))
  | mapbnd f d (Var (v, va)) = return (Var (v, va));

fun red (Abs (uu, uv, s)) (i :: is) js = red s is (i :: js)
  | red t [] [] = return t
  | red (Const (v, va)) (vb :: vc) jn =
    bindM (mapbnd (nth jn) (0 : IntInf.int) (Const (v, va)))
      (fn t => return (app t (vb :: vc)))
  | red (Const (v, va)) is (vb :: vc) =
    bindM (mapbnd (nth (vb :: vc)) (0 : IntInf.int) (Const (v, va)))
      (fn t => return (app t is))
  | red (Free (v, va)) (vb :: vc) jn =
    bindM (mapbnd (nth jn) (0 : IntInf.int) (Free (v, va)))
      (fn t => return (app t (vb :: vc)))
  | red (Free (v, va)) is (vb :: vc) =
    bindM (mapbnd (nth (vb :: vc)) (0 : IntInf.int) (Free (v, va)))
      (fn t => return (app t is))
  | red (Var (v, va)) (vb :: vc) jn =
    bindM (mapbnd (nth jn) (0 : IntInf.int) (Var (v, va)))
      (fn t => return (app t (vb :: vc)))
  | red (Var (v, va)) is (vb :: vc) =
    bindM (mapbnd (nth (vb :: vc)) (0 : IntInf.int) (Var (v, va)))
      (fn t => return (app t is))
  | red (Bound v) (va :: vb) jn =
    bindM (mapbnd (nth jn) (0 : IntInf.int) (Bound v))
      (fn t => return (app t (va :: vb)))
  | red (Bound v) is (va :: vb) =
    bindM (mapbnd (nth (va :: vb)) (0 : IntInf.int) (Bound v))
      (fn t => return (app t is))
  | red (v $ va) (vb :: vc) jn =
    bindM (mapbnd (nth jn) (0 : IntInf.int) (v $ va))
      (fn t => return (app t (vb :: vc)))
  | red (v $ va) is (vb :: vc) =
    bindM (mapbnd (nth (vb :: vc)) (0 : IntInf.int) (v $ va))
      (fn t => return (app t is))
  | red t [] (v :: va) =
    bindM (mapbnd (nth (v :: va)) (0 : IntInf.int) t)
      (fn ta => return (app ta []));

fun loose_bvar1 (Bound i) k = ((i : IntInf.int) = k)
  | loose_bvar1 (f $ t) k = loose_bvar1 f k orelse loose_bvar1 t k
  | loose_bvar1 (Abs (uu, uv, t)) k =
    loose_bvar1 t (IntInf.+ (k, (1 : IntInf.int)))
  | loose_bvar1 (Const (v, va)) ux = false
  | loose_bvar1 (Free (v, va)) ux = false
  | loose_bvar1 (Var (v, va)) ux = false;

fun is_dependent t = loose_bvar1 t (0 : IntInf.int);

fun eta_contract (Abs (a, t, body)) =
  let
    val bodya = eta_contract body;
  in
    (case bodya of Const (_, _) => Abs (a, t, bodya)
      | Free (_, _) => Abs (a, t, bodya) | Var (_, _) => Abs (a, t, bodya)
      | Bound _ => Abs (a, t, bodya) | Abs (_, _, _) => Abs (a, t, bodya)
      | _ $ Const (_, _) => Abs (a, t, bodya)
      | _ $ Free (_, _) => Abs (a, t, bodya)
      | _ $ Var (_, _) => Abs (a, t, bodya)
      | f $ Bound i =>
        (if ((i : IntInf.int) = (0 : IntInf.int)) andalso not (is_dependent f)
          then decr (0 : IntInf.int) f else Abs (a, t, bodya))
      | _ $ Abs (_, _, _) => Abs (a, t, bodya)
      | _ $ (_ $ _) => Abs (a, t, bodya))
  end
  | eta_contract (t $ u) = eta_contract t $ eta_contract u
  | eta_contract (Const (v, va)) = Const (v, va)
  | eta_contract (Free (v, va)) = Free (v, va)
  | eta_contract (Var (v, va)) = Var (v, va)
  | eta_contract (Bound v) = Bound v;

fun aconv_term (t1 $ u1) (t2 $ u2) = aconv_term t1 t2 andalso aconv_term u1 u2
  | aconv_term (Abs (uu, t1a, t1)) (Abs (uv, t2a, t2)) =
    aconv_term t1 t2 andalso ((t1a : typ) = t2a)
  | aconv_term (Const (v, va)) a2 = (((Const (v, va)) : term) = a2)
  | aconv_term (Free (v, va)) a2 = (((Free (v, va)) : term) = a2)
  | aconv_term (Var (v, va)) a2 = (((Var (v, va)) : term) = a2)
  | aconv_term (Bound v) a2 = (((Bound v) : term) = a2)
  | aconv_term (Abs (v, va, vb)) (Const (vc, vd)) =
    (((Abs (v, va, vb)) : term) = (Const (vc, vd)))
  | aconv_term (Abs (v, va, vb)) (Free (vc, vd)) =
    (((Abs (v, va, vb)) : term) = (Free (vc, vd)))
  | aconv_term (Abs (v, va, vb)) (Var (vc, vd)) =
    (((Abs (v, va, vb)) : term) = (Var (vc, vd)))
  | aconv_term (Abs (v, va, vb)) (Bound vc) =
    (((Abs (v, va, vb)) : term) = (Bound vc))
  | aconv_term (Abs (v, va, vb)) (vc $ vd) =
    (((Abs (v, va, vb)) : term) = (vc $ vd))
  | aconv_term a1 (Const (v, va)) = ((a1 : term) = (Const (v, va)))
  | aconv_term a1 (Free (v, va)) = ((a1 : term) = (Free (v, va)))
  | aconv_term a1 (Var (v, va)) = ((a1 : term) = (Var (v, va)))
  | aconv_term a1 (Bound v) = ((a1 : term) = (Bound v))
  | aconv_term (vc $ vd) (Abs (v, va, vb)) =
    (((vc $ vd) : term) = (Abs (v, va, vb)));

fun aeconv t u =
  aconv_term t u orelse aconv_term (eta_contract t) (eta_contract u);

fun zip_eq [] [] = return []
  | zip_eq (x :: xs) (y :: ys) =
    bindM (zip_eq xs ys) (fn zs => return ((x, y) :: zs))
  | zip_eq (v :: va) [] = raisea Unequal_Lengths
  | zip_eq [] (v :: va) = raisea Unequal_Lengths;

fun incr_aux d (Bound i) =
  (if IntInf.< (i, d) then Bound i else Bound (IntInf.+ (i, (1 : IntInf.int))))
  | incr_aux d (Abs (s, ta, t)) =
    Abs (s, ta, incr_aux (IntInf.+ (d, (1 : IntInf.int))) t)
  | incr_aux d (u1 $ u2) = incr_aux d u1 $ incr_aux d u2
  | incr_aux d (Const (v, va)) = Const (v, va)
  | incr_aux d (Free (v, va)) = Free (v, va)
  | incr_aux d (Var (v, va)) = Var (v, va);

fun incr t = incr_aux (0 : IntInf.int) t;

fun equal_prod A_ B_ (x1, x2) (y1, y2) = eq A_ x1 y1 andalso eq B_ x2 y2;

fun of_sort alg t s =
  (if null s then return true
    else (case t
           of Type (a, ts) =>
             handlea
               (bindM (mg_domain alg a s)
                 (fn ss => allM (fn (aa, b) => of_sort alg aa b) (zip ts ss)))
               (fn e =>
                 (case e of Unif _ => raisea e | Pattern => raisea e
                   | Match => raisea e | TUnify => raisea e
                   | Type_Match => raisea e | Class_Error _ => return false
                   | Type_Error (_, _, _) => raisea e
                   | Term_Error (_, _) => raisea e | Failure _ => raisea e
                   | Subscript => raisea e | Unequal_Lengths => raisea e
                   | Dup _ => raisea e))
           | TFree (_, sa) => return (sort_le alg sa s)
           | TVar (_, sa) => return (sort_le alg sa s)));

fun typ_match alg (TVar (v, s)) t subs =
  bindM (type_lookup subs v s)
    (fn a =>
      (case a
        of NONE =>
          bindM (of_sort alg t s)
            (fn b =>
              (if b then update_new (v, (s, t)) subs else raisea Type_Match))
        | SOME u =>
          (if ((u : typ) = t) then return subs else raisea Type_Match)))
  | typ_match alg (Type (a, ts)) (Type (b, us)) subs =
    (if not ((a : string) = b) then raisea Type_Match
      else foldM (fn (aa, ba) => typ_match alg aa ba) (zip ts us) subs)
  | typ_match alg (TFree (a, sa)) (TFree (b, s)) subs =
    (if equal_prod equal_literal (equal_list equal_literal) (a, sa) (b, s)
      then return subs else raisea Type_Match)
  | typ_match alg (Type (v, va)) (TFree (vb, vc)) subs = raisea Type_Match
  | typ_match alg (Type (v, va)) (TVar (vb, vc)) subs = raisea Type_Match
  | typ_match alg (TFree (v, va)) (Type (vb, vc)) subs = raisea Type_Match
  | typ_match alg (TFree (v, va)) (TVar (vb, vc)) subs = raisea Type_Match;

fun typ_match_m alg t u tye =
  handlea (typ_match alg t u tye)
    (fn e =>
      (case e of Unif _ => raisea e | Pattern => raisea e | Match => raisea e
        | TUnify => raisea e | Type_Match => raisea Match
        | Class_Error _ => raisea e | Type_Error (_, _, _) => raisea e
        | Term_Error (_, _) => raisea e | Failure _ => raisea e
        | Subscript => raisea e | Unequal_Lengths => raisea e
        | Dup _ => raisea e));

fun add_loose_bnos (Bound i) lev js =
  (if IntInf.< (i, lev) then js
    else insert equal_integer (IntInf.- (i, lev)) js)
  | add_loose_bnos (Abs (uu, uv, t)) lev js =
    add_loose_bnos t (IntInf.+ (lev, (1 : IntInf.int))) js
  | add_loose_bnos (f $ t) lev js =
    add_loose_bnos f lev (add_loose_bnos t lev js)
  | add_loose_bnos (Const (v, va)) ux js = js
  | add_loose_bnos (Free (v, va)) ux js = js
  | add_loose_bnos (Var (v, va)) ux js = js;

fun loose_bnos t = add_loose_bnos t (0 : IntInf.int) [];

fun downto0 (i :: is) n =
  ((i : IntInf.int) = n) andalso downto0 is (IntInf.- (n, (1 : IntInf.int)))
  | downto0 [] n = ((n : IntInf.int) = (~1 : IntInf.int));

fun match_bind itms binders ixn ta is t =
  let
    val js = loose_bnos t;
  in
    (if null is
      then (if null js then update_new (ixn, (ta, t)) itms else raisea Match)
      else (if subset equal_integer js is
             then bindM (if downto0 is
                              (IntInf.- (ilength binders, (1 : IntInf.int)))
                          then return t else mapbnd (idx is) (0 : IntInf.int) t)
                    (fn tb =>
                      bindM (mkabs binders is tb)
                        (fn u => update_new (ixn, (ta, u)) itms))
             else raisea Match))
  end;

fun subst_type_aux tye (Type (a, ts)) =
  bindM (mapM (subst_type_aux tye) ts) (fn tsa => return (Type (a, tsa)))
  | subst_type_aux tye (TVar (v, s)) =
    bindM (type_lookup tye v s)
      (fn a => (case a of NONE => return (TVar (v, s)) | SOME aa => return aa))
  | subst_type_aux tye (TFree (v, va)) = return (TFree (v, va));

fun subst_type tye t =
  (if Vartab.is_empty tye then return t else subst_type_aux tye t);

fun lookup1 te xi t =
  (case Vartab.lookup te xi of NONE => return NONE
    | SOME (u, ta) =>
      (if ((t : typ) = u) then return (SOME ta) else var_clash xi t u));

fun mtch alg binders pat obj env =
  let
    val (iTs, itms) = env;
  in
    (if is_Abs pat
      then (case pat of Const (_, _) => raisea (Failure "mtch")
             | Free (_, _) => raisea (Failure "mtch")
             | Var (_, _) => raisea (Failure "mtch")
             | Bound _ => raisea (Failure "mtch")
             | Abs (ns, ts, tsa) =>
               (if is_Abs obj
                 then (case obj of Const (_, _) => raisea (Failure "mtch")
                        | Free (_, _) => raisea (Failure "mtch")
                        | Var (_, _) => raisea (Failure "mtch")
                        | Bound _ => raisea (Failure "mtch")
                        | Abs (nt, tt, tta) =>
                          mtch alg ((nt, tt) :: binders) tsa tta env
                        | _ $ _ => raisea (Failure "mtch"))
                 else bindM (subst_type iTs ts)
                        (fn tt =>
                          mtch alg ((ns, tt) :: binders) tsa
                            (incr obj $ Bound (0 : IntInf.int)) env))
             | _ $ _ => raisea (Failure "mtch"))
      else (if is_Abs obj
             then (case obj of Const (_, _) => raisea (Failure "mtch")
                    | Free (_, _) => raisea (Failure "mtch")
                    | Var (_, _) => raisea (Failure "mtch")
                    | Bound _ => raisea (Failure "mtch")
                    | Abs (nt, tt, tta) =>
                      mtch alg ((nt, tt) :: binders)
                        (incr pat $ Bound (0 : IntInf.int)) tta env
                    | _ $ _ => raisea (Failure "mtch"))
             else let
                    val (ph, pargs) = strip_comb pat;
                  in
                    (if is_Var ph
                      then (case ph of Const (_, _) => raisea (Failure "mtch")
                             | Free (_, _) => raisea (Failure "mtch")
                             | Var (ixn, t) =>
                               bindM (ints_of pargs)
                                 (fn is =>
                                   bindM (lookup1 itms ixn t)
                                     (fn a =>
                                       (case a
 of NONE =>
   bindM (match_bind itms binders ixn t is obj)
     (fn itmsa => return (iTs, itmsa))
 | SOME u =>
   bindM (red u is [])
     (fn ua => (if aeconv obj ua then return env else raisea Match)))))
                             | Bound _ => raisea (Failure "mtch")
                             | Abs (_, _, _) => raisea (Failure "mtch")
                             | _ $ _ => raisea (Failure "mtch"))
                      else let
                             val (oh, oargs) = strip_comb obj;
                           in
                             (case (ph, oh)
                               of (Const (a, ta), Const (b, tb)) =>
                                 (if not ((a : string) = b) then raisea Match
                                   else bindM (typ_match_m alg ta tb iTs)
  (fn iTsa =>
    handlea
      (bindM (zip_eq pargs oargs)
        (fn ps =>
          foldM (fn (aa, ba) => mtch alg binders aa ba) ps (iTsa, itms)))
      (fn e =>
        (case e of Unif _ => raisea e | Pattern => raisea e | Match => raisea e
          | TUnify => raisea e | Type_Match => raisea e
          | Class_Error _ => raisea e | Type_Error (_, _, _) => raisea e
          | Term_Error (_, _) => raisea e | Failure _ => raisea e
          | Subscript => raisea e | Unequal_Lengths => raisea Match
          | Dup _ => raisea e))))
                               | (Const (_, _), Free (_, _)) => raisea Match
                               | (Const (_, _), Var (_, _)) => raisea Match
                               | (Const (_, _), Bound _) => raisea Match
                               | (Const (_, _), Abs (_, _, _)) => raisea Pattern
                               | (Const (_, _), _ $ _) => raisea Match
                               | (Free (_, _), Const (_, _)) => raisea Match
                               | (Free (a, ta), Free (b, tb)) =>
                                 (if not ((a : string) = b) then raisea Match
                                   else bindM (typ_match_m alg ta tb iTs)
  (fn iTsa =>
    handlea
      (bindM (zip_eq pargs oargs)
        (fn ps =>
          foldM (fn (aa, ba) => mtch alg binders aa ba) ps (iTsa, itms)))
      (fn e =>
        (case e of Unif _ => raisea e | Pattern => raisea e | Match => raisea e
          | TUnify => raisea e | Type_Match => raisea e
          | Class_Error _ => raisea e | Type_Error (_, _, _) => raisea e
          | Term_Error (_, _) => raisea e | Failure _ => raisea e
          | Subscript => raisea e | Unequal_Lengths => raisea Match
          | Dup _ => raisea e))))
                               | (Free (_, _), Var (_, _)) => raisea Match
                               | (Free (_, _), Bound _) => raisea Match
                               | (Free (_, _), Abs (_, _, _)) => raisea Pattern
                               | (Free (_, _), _ $ _) => raisea Match
                               | (Var (_, _), Const (_, _)) => raisea Match
                               | (Var (_, _), Free (_, _)) => raisea Match
                               | (Var (_, _), Var (_, _)) => raisea Match
                               | (Var (_, _), Bound _) => raisea Match
                               | (Var (_, _), Abs (_, _, _)) => raisea Pattern
                               | (Var (_, _), _ $ _) => raisea Match
                               | (Bound _, Const (_, _)) => raisea Match
                               | (Bound _, Free (_, _)) => raisea Match
                               | (Bound _, Var (_, _)) => raisea Match
                               | (Bound i, Bound j) =>
                                 (if not ((i : IntInf.int) = j)
                                   then raisea Match
                                   else handlea
  (bindM (zip_eq pargs oargs)
    (fn ps => foldM (fn (a, b) => mtch alg binders a b) ps (iTs, itms)))
  (fn e =>
    (case e of Unif _ => raisea e | Pattern => raisea e | Match => raisea e
      | TUnify => raisea e | Type_Match => raisea e | Class_Error _ => raisea e
      | Type_Error (_, _, _) => raisea e | Term_Error (_, _) => raisea e
      | Failure _ => raisea e | Subscript => raisea e
      | Unequal_Lengths => raisea Match | Dup _ => raisea e)))
                               | (Bound _, Abs (_, _, _)) => raisea Pattern
                               | (Bound _, _ $ _) => raisea Match
                               | (Abs (_, _, _), _) => raisea Pattern
                               | (_ $ _, Const (_, _)) => raisea Match
                               | (_ $ _, Free (_, _)) => raisea Match
                               | (_ $ _, Var (_, _)) => raisea Match
                               | (_ $ _, Bound _) => raisea Match
                               | (_ $ _, Abs (_, _, _)) => raisea Pattern
                               | (_ $ _, _ $ _) => raisea Match)
                           end)
                  end))
  end;

fun proj s env binders is =
  (if downto0 is (IntInf.- (ilength binders, (1 : IntInf.int)))
    then return (s, env) else pr is s env (0 : IntInf.int) binders);

fun existsM p [] = return false
  | existsM p (x :: xs) =
    bindM (p x) (fn b => (if b then return true else existsM p xs));

fun type_occurs v tye t =
  (case t of Type (_, a) => existsM (type_occurs v tye) a
    | TFree (_, _) => return false
    | TVar (w, s) =>
      (if equal_prod equal_literal equal_integer v w then return true
        else bindM (type_lookup tye w s)
               (fn a =>
                 (case a of NONE => return false
                   | SOME aa => type_occurs v tye aa))));

fun unify_aux alg ty1 ty2 st =
  let
    val (tye, cnt) = st;
  in
    bindM (devar tye ty1)
      (fn t =>
        bindM (devar tye ty2)
          (fn u =>
            (case (t, u)
              of (Type (literal, lista), Type (b, us)) =>
                (if not ((literal : string) = b) then raisea TUnify
                  else foldM (fn (a, ba) => unify_aux alg a ba) (zip lista us)
                         st)
              | (Type (_, _), TFree (_, _)) =>
                (if ((t : typ) = u) then return st else raisea TUnify)
              | (Type (_, _), TVar (v, s)) =>
                bindM (type_occurs v tye t)
                  (fn b =>
                    (if b then raisea TUnify
                      else bindM (update_new (v, (s, t)) tye)
                             (fn tyea => meet alg t s (tyea, cnt))))
              | (TFree (_, _), Type (_, _)) =>
                (if ((t : typ) = u) then return st else raisea TUnify)
              | (TFree (_, _), TFree (_, _)) =>
                (if ((t : typ) = u) then return st else raisea TUnify)
              | (TFree (_, _), TVar (v, s)) =>
                bindM (type_occurs v tye t)
                  (fn b =>
                    (if b then raisea TUnify
                      else bindM (update_new (v, (s, t)) tye)
                             (fn tyea => meet alg t s (tyea, cnt))))
              | (TVar (v, s1), Type (_, _)) =>
                bindM (type_occurs v tye u)
                  (fn b =>
                    (if b then raisea TUnify
                      else bindM (update_new (v, (s1, u)) tye)
                             (fn tyea => meet alg u s1 (tyea, cnt))))
              | (TVar (v, s1), TFree (_, _)) =>
                bindM (type_occurs v tye u)
                  (fn b =>
                    (if b then raisea TUnify
                      else bindM (update_new (v, (s1, u)) tye)
                             (fn tyea => meet alg u s1 (tyea, cnt))))
              | (TVar (v, s1), TVar (w, s2)) =>
                (if equal_prod equal_literal equal_integer v w
                  then (if equal_lista equal_literal s1 s2 then return st
                         else tvar_clash v s1 s2)
                  else (if sort_le alg s1 s2
                         then bindM (update_new (w, (s2, t)) tye)
                                (fn tyea => return (tyea, cnt))
                         else (if sort_le alg s2 s1
                                then bindM (update_new (v, (s1, u)) tye)
                                       (fn tyea => return (tyea, cnt))
                                else let
                                       val (s, cnta) =
 gen_tyvar (inter_sort alg s1 s2) cnt;
                                     in
                                       bindM (update_new (w, (s2, s)) tye)
 (fn tyea =>
   bindM (update_new (v, (s1, s)) tyea) (fn tyeb => return (tyeb, cnta)))
                                     end))))))
  end;

fun type_unify alg t u st = unify_aux alg t u st;

fun unify_types alg t u env =
  (if ((t : typ) = u) then return env
    else handlea
           (bindM (type_unify alg u t (Envir.type_env env, Envir.maxidx_of env))
             (fn (tye, maxidx) =>
               return
                 (Envir.Envir {maxidx = maxidx, tenv = (Envir.term_env env),
                   tyenv = tye})))
           (fn e =>
             (case e of Unif _ => raisea e | Pattern => raisea e
               | Match => raisea e
               | TUnify => raisea (Unif (Typ_Clash (Envir.type_env env, t, u)))
               | Type_Match => raisea e | Class_Error _ => raisea e
               | Type_Error (_, _, _) => raisea e
               | Term_Error (_, _) => raisea e | Failure _ => raisea e
               | Subscript => raisea e | Unequal_Lengths => raisea e
               | Dup _ => raisea e)));

fun rigid_name h =
  (case h of Const (c, _) => c | Free (f, _) => f | Var (_, _) => ""
    | Bound _ => "" | Abs (_, _, _) => "" | _ $ _ => "");

fun rigid_clash binders h1 h2 =
  (case (h1, h2)
    of (Const (_, _), Const (_, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Const (_, _), Free (_, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Const (_, _), Var (_, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Const (_, _), Bound i) =>
      raisea (Unif (Clash_B (binders, i, rigid_name h1)))
    | (Const (_, _), Abs (_, _, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Const (_, _), _ $ _) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Free (_, _), Const (_, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Free (_, _), Free (_, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Free (_, _), Var (_, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Free (_, _), Bound i) =>
      raisea (Unif (Clash_B (binders, i, rigid_name h1)))
    | (Free (_, _), Abs (_, _, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Free (_, _), _ $ _) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Var (_, _), Const (_, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Var (_, _), Free (_, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Var (_, _), Var (_, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Var (_, _), Bound i) =>
      raisea (Unif (Clash_B (binders, i, rigid_name h1)))
    | (Var (_, _), Abs (_, _, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Var (_, _), _ $ _) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Bound i, Const (_, _)) =>
      raisea (Unif (Clash_B (binders, i, rigid_name h2)))
    | (Bound i, Free (_, _)) =>
      raisea (Unif (Clash_B (binders, i, rigid_name h2)))
    | (Bound i, Var (_, _)) =>
      raisea (Unif (Clash_B (binders, i, rigid_name h2)))
    | (Bound i, Bound j) => raisea (Unif (Clash_BB (binders, i, j)))
    | (Bound i, Abs (_, _, _)) =>
      raisea (Unif (Clash_B (binders, i, rigid_name h2)))
    | (Bound i, _ $ _) => raisea (Unif (Clash_B (binders, i, rigid_name h2)))
    | (Abs (_, _, _), Const (_, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Abs (_, _, _), Free (_, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Abs (_, _, _), Var (_, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Abs (_, _, _), Bound i) =>
      raisea (Unif (Clash_B (binders, i, rigid_name h1)))
    | (Abs (_, _, _), Abs (_, _, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (Abs (_, _, _), _ $ _) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (_ $ _, Const (_, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (_ $ _, Free (_, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (_ $ _, Var (_, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (_ $ _, Bound i) => raisea (Unif (Clash_B (binders, i, rigid_name h1)))
    | (_ $ _, Abs (_, _, _)) =>
      raisea (Unif (Clash (rigid_name h1, rigid_name h2)))
    | (_ $ _, _ $ _) => raisea (Unif (Clash (rigid_name h1, rigid_name h2))));

fun rigid_occurs f t env =
  bindM (head_norm env t)
    (fn ta =>
      (case ta
        of Const (_, _) =>
          (case strip_comb ta
            of (Const (_, _), ts) => existsM (fn u => rigid_occurs f u env) ts
            | (Free (_, _), ts) => existsM (fn u => rigid_occurs f u env) ts
            | (Var (g, _), ts) =>
              (if equal_prod equal_literal equal_integer g f
                then handlea (bindM (ints_ofa env ts) (fn _ => return true))
                       (fn e =>
                         (case e of Unif _ => raisea e | Pattern => return false
                           | Match => raisea e | TUnify => raisea e
                           | Type_Match => raisea e | Class_Error _ => raisea e
                           | Type_Error (_, _, _) => raisea e
                           | Term_Error (_, _) => raisea e
                           | Failure _ => raisea e | Subscript => raisea e
                           | Unequal_Lengths => raisea e | Dup _ => raisea e))
                else return false)
            | (Bound _, ts) => existsM (fn u => rigid_occurs f u env) ts
            | (Abs (_, _, _), _) => return false
            | (_ $ _, ts) => existsM (fn u => rigid_occurs f u env) ts)
        | Free (_, _) =>
          (case strip_comb ta
            of (Const (_, _), ts) => existsM (fn u => rigid_occurs f u env) ts
            | (Free (_, _), ts) => existsM (fn u => rigid_occurs f u env) ts
            | (Var (g, _), ts) =>
              (if equal_prod equal_literal equal_integer g f
                then handlea (bindM (ints_ofa env ts) (fn _ => return true))
                       (fn e =>
                         (case e of Unif _ => raisea e | Pattern => return false
                           | Match => raisea e | TUnify => raisea e
                           | Type_Match => raisea e | Class_Error _ => raisea e
                           | Type_Error (_, _, _) => raisea e
                           | Term_Error (_, _) => raisea e
                           | Failure _ => raisea e | Subscript => raisea e
                           | Unequal_Lengths => raisea e | Dup _ => raisea e))
                else return false)
            | (Bound _, ts) => existsM (fn u => rigid_occurs f u env) ts
            | (Abs (_, _, _), _) => return false
            | (_ $ _, ts) => existsM (fn u => rigid_occurs f u env) ts)
        | Var (_, _) =>
          (case strip_comb ta
            of (Const (_, _), ts) => existsM (fn u => rigid_occurs f u env) ts
            | (Free (_, _), ts) => existsM (fn u => rigid_occurs f u env) ts
            | (Var (g, _), ts) =>
              (if equal_prod equal_literal equal_integer g f
                then handlea (bindM (ints_ofa env ts) (fn _ => return true))
                       (fn e =>
                         (case e of Unif _ => raisea e | Pattern => return false
                           | Match => raisea e | TUnify => raisea e
                           | Type_Match => raisea e | Class_Error _ => raisea e
                           | Type_Error (_, _, _) => raisea e
                           | Term_Error (_, _) => raisea e
                           | Failure _ => raisea e | Subscript => raisea e
                           | Unequal_Lengths => raisea e | Dup _ => raisea e))
                else return false)
            | (Bound _, ts) => existsM (fn u => rigid_occurs f u env) ts
            | (Abs (_, _, _), _) => return false
            | (_ $ _, ts) => existsM (fn u => rigid_occurs f u env) ts)
        | Bound _ =>
          (case strip_comb ta
            of (Const (_, _), ts) => existsM (fn u => rigid_occurs f u env) ts
            | (Free (_, _), ts) => existsM (fn u => rigid_occurs f u env) ts
            | (Var (g, _), ts) =>
              (if equal_prod equal_literal equal_integer g f
                then handlea (bindM (ints_ofa env ts) (fn _ => return true))
                       (fn e =>
                         (case e of Unif _ => raisea e | Pattern => return false
                           | Match => raisea e | TUnify => raisea e
                           | Type_Match => raisea e | Class_Error _ => raisea e
                           | Type_Error (_, _, _) => raisea e
                           | Term_Error (_, _) => raisea e
                           | Failure _ => raisea e | Subscript => raisea e
                           | Unequal_Lengths => raisea e | Dup _ => raisea e))
                else return false)
            | (Bound _, ts) => existsM (fn u => rigid_occurs f u env) ts
            | (Abs (_, _, _), _) => return false
            | (_ $ _, ts) => existsM (fn u => rigid_occurs f u env) ts)
        | Abs (_, _, u) => rigid_occurs f u env
        | _ $ _ =>
          (case strip_comb ta
            of (Const (_, _), ts) => existsM (fn u => rigid_occurs f u env) ts
            | (Free (_, _), ts) => existsM (fn u => rigid_occurs f u env) ts
            | (Var (g, _), ts) =>
              (if equal_prod equal_literal equal_integer g f
                then handlea (bindM (ints_ofa env ts) (fn _ => return true))
                       (fn e =>
                         (case e of Unif _ => raisea e | Pattern => return false
                           | Match => raisea e | TUnify => raisea e
                           | Type_Match => raisea e | Class_Error _ => raisea e
                           | Type_Error (_, _, _) => raisea e
                           | Term_Error (_, _) => raisea e
                           | Failure _ => raisea e | Subscript => raisea e
                           | Unequal_Lengths => raisea e | Dup _ => raisea e))
                else return false)
            | (Bound _, ts) => existsM (fn u => rigid_occurs f u env) ts
            | (Abs (_, _, _), _) => return false
            | (_ $ _, ts) => existsM (fn u => rigid_occurs f u env) ts)));

fun occurs f t env =
  (case t of Const (_, _) => return false | Free (_, _) => return false
    | Var (g, ta) =>
      bindM (lookup env g ta)
        (fn a =>
          (case a of NONE => return (equal_prod equal_literal equal_integer f g)
            | SOME u => occurs f u env))
    | Bound _ => return false | Abs (_, _, u) => occurs f u env
    | t1 $ t2 =>
      bindM (occurs f t1 env)
        (fn b => (if b then return true else occurs f t2 env)));

fun flexrigid env binders f fty is t =
  bindM (occurs f t env)
    (fn b =>
      (if b then bindM (rigid_occurs f t env)
                   (fn ba =>
                     (if ba
                       then raisea (Unif (Ocheck_Fail (f, t, binders, env)))
                       else raisea Pattern))
        else handlea
               (bindM (proj t env binders is)
                 (fn (u, enva) =>
                   bindM (mkabs binders is u)
                     (fn ua => update (f, fty) ua enva)))
               (fn e =>
                 (case e
                   of Unif _ =>
                     raisea (Unif (Proj_Fail (env, binders, f, is, t)))
                   | Pattern => raisea e | Match => raisea e
                   | TUnify => raisea e | Type_Match => raisea e
                   | Class_Error _ => raisea e
                   | Type_Error (_, _, _) => raisea e
                   | Term_Error (_, _) => raisea e | Failure _ => raisea e
                   | Subscript => raisea e | Unequal_Lengths => raisea e
                   | Dup _ => raisea e))));

fun indexname_less g f =
  IntInf.< (snd g, snd f) orelse
    (((snd g) : IntInf.int) = (snd f)) andalso (((fst g) : string) < (fst f));

fun flexflex2 env binders f fty is g gty js =
  (if indexname_less g f then ff env binders f fty is g gty js
    else ff env binders g gty js f fty is);

fun mk_new_hnf env binders is f t js =
  bindM (type_of_G env t (ilength is) js)
    (fn gty =>
      let
        val (enva, g) = genvar (fst f) env gty;
      in
        bindM (mk_hnf binders is g js) (fn ta => update (f, t) ta enva)
      end);

fun mk_ff_list_aux [] [] uu = return []
  | mk_ff_list_aux (i :: is) (j :: js) k =
    (if ((i : IntInf.int) = j)
      then bindM (mk_ff_list_aux is js (IntInf.- (k, (1 : IntInf.int))))
             (fn ks => return (k :: ks))
      else mk_ff_list_aux is js (IntInf.- (k, (1 : IntInf.int))))
  | mk_ff_list_aux (v :: va) [] ux = raisea (Failure "mk_ff_list")
  | mk_ff_list_aux [] (v :: va) ux = raisea (Failure "mk_ff_list");

fun mk_ff_list is js =
  mk_ff_list_aux is js (IntInf.- (ilength is, (1 : IntInf.int)));

fun flexflex1 env binders f fty is js =
  (if equal_lista equal_integer is js then return env
    else bindM (mk_ff_list is js) (mk_new_hnf env binders is f fty));

fun unif alg binders s t env =
  bindM (head_norm env s)
    (fn sa =>
      bindM (head_norm env t)
        (fn ta =>
          (if is_Abs sa andalso is_Abs ta
            then (case (sa, ta) of (Const (_, _), _) => raisea (Failure "unif")
                   | (Free (_, _), _) => raisea (Failure "unif")
                   | (Var (_, _), _) => raisea (Failure "unif")
                   | (Bound _, _) => raisea (Failure "unif")
                   | (Abs (_, _, _), Const (_, _)) => raisea (Failure "unif")
                   | (Abs (_, _, _), Free (_, _)) => raisea (Failure "unif")
                   | (Abs (_, _, _), Var (_, _)) => raisea (Failure "unif")
                   | (Abs (_, _, _), Bound _) => raisea (Failure "unif")
                   | (Abs (ns, ts, tsa), Abs (nt, tt, tta)) =>
                     let
                       val name = (if ((ns : string) = "") then nt else ns);
                     in
                       bindM (unify_types alg ts tt env)
                         (unif alg ((name, ts) :: binders) tsa tta)
                     end
                   | (Abs (_, _, _), _ $ _) => raisea (Failure "unif")
                   | (_ $ _, _) => raisea (Failure "unif"))
            else (if is_Abs sa
                   then (case sa of Const (_, _) => raisea (Failure "unif")
                          | Free (_, _) => raisea (Failure "unif")
                          | Var (_, _) => raisea (Failure "unif")
                          | Bound _ => raisea (Failure "unif")
                          | Abs (ns, ts, tsa) =>
                            unif alg ((ns, ts) :: binders) tsa
                              (incr ta $ Bound (0 : IntInf.int)) env
                          | _ $ _ => raisea (Failure "unif"))
                   else (if is_Abs ta
                          then (case ta
                                 of Const (_, _) => raisea (Failure "unif")
                                 | Free (_, _) => raisea (Failure "unif")
                                 | Var (_, _) => raisea (Failure "unif")
                                 | Bound _ => raisea (Failure "unif")
                                 | Abs (nt, tt, tta) =>
                                   unif alg ((nt, tt) :: binders)
                                     (incr sa $ Bound (0 : IntInf.int)) tta env
                                 | _ $ _ => raisea (Failure "unif"))
                          else let
                                 val (hs, ss) = strip_comb sa;
                                 val (ht, ts) = strip_comb ta;
                               in
                                 (if is_Var hs andalso is_Var ht
                                   then (case (hs, ht)
  of (Const (_, _), _) => raisea (Failure "unif")
  | (Free (_, _), _) => raisea (Failure "unif")
  | (Var (_, _), Const (_, _)) => raisea (Failure "unif")
  | (Var (_, _), Free (_, _)) => raisea (Failure "unif")
  | (Var (f, fty), Var (g, gty)) =>
    bindM (ints_ofa env ss)
      (fn is =>
        bindM (ints_ofa env ts)
          (fn js =>
            (if equal_prod equal_literal equal_integer f g
              then flexflex1 env binders f fty is js
              else flexflex2 env binders f fty is g gty js)))
  | (Var (_, _), Bound _) => raisea (Failure "unif")
  | (Var (_, _), Abs (_, _, _)) => raisea (Failure "unif")
  | (Var (_, _), _ $ _) => raisea (Failure "unif")
  | (Bound _, _) => raisea (Failure "unif")
  | (Abs (_, _, _), _) => raisea (Failure "unif")
  | (_ $ _, _) => raisea (Failure "unif"))
                                   else (if is_Var hs
  then (case hs of Const (_, _) => raisea (Failure "unif")
         | Free (_, _) => raisea (Failure "unif")
         | Var (f, fty) =>
           bindM (ints_ofa env ss) (fn is => flexrigid env binders f fty is ta)
         | Bound _ => raisea (Failure "unif")
         | Abs (_, _, _) => raisea (Failure "unif")
         | _ $ _ => raisea (Failure "unif"))
  else (if is_Var ht
         then (case ht of Const (_, _) => raisea (Failure "unif")
                | Free (_, _) => raisea (Failure "unif")
                | Var (f, fty) =>
                  bindM (ints_ofa env ts)
                    (fn is => flexrigid env binders f fty is sa)
                | Bound _ => raisea (Failure "unif")
                | Abs (_, _, _) => raisea (Failure "unif")
                | _ $ _ => raisea (Failure "unif"))
         else (if is_Abs hs orelse is_Abs ht then raisea Pattern
                else (case (hs, ht)
                       of (Const (a, taa), Const (b, tb)) =>
                         (if not ((a : string) = b)
                           then raisea (Unif (Clash (a, b)))
                           else bindM (unify_types alg taa tb env)
                                  (fn enva =>
                                    bindM (zip_eq ss ts)
                                      (fn ps =>
foldM (fn (aa, ba) => unif alg binders aa ba) ps enva)))
                       | (Const (_, _), Free (_, _)) =>
                         rigid_clash binders hs ht
                       | (Const (_, _), Var (_, _)) => rigid_clash binders hs ht
                       | (Const (_, _), Bound _) => rigid_clash binders hs ht
                       | (Const (_, _), Abs (_, _, _)) =>
                         rigid_clash binders hs ht
                       | (Const (_, _), _ $ _) => rigid_clash binders hs ht
                       | (Free (_, _), Const (_, _)) =>
                         rigid_clash binders hs ht
                       | (Free (a, taa), Free (b, tb)) =>
                         (if not ((a : string) = b)
                           then raisea (Unif (Clash (a, b)))
                           else bindM (unify_types alg taa tb env)
                                  (fn enva =>
                                    bindM (zip_eq ss ts)
                                      (fn ps =>
foldM (fn (aa, ba) => unif alg binders aa ba) ps enva)))
                       | (Free (_, _), Var (_, _)) => rigid_clash binders hs ht
                       | (Free (_, _), Bound _) => rigid_clash binders hs ht
                       | (Free (_, _), Abs (_, _, _)) =>
                         rigid_clash binders hs ht
                       | (Free (_, _), _ $ _) => rigid_clash binders hs ht
                       | (Var (_, _), _) => rigid_clash binders hs ht
                       | (Bound _, Const (_, _)) => rigid_clash binders hs ht
                       | (Bound _, Free (_, _)) => rigid_clash binders hs ht
                       | (Bound _, Var (_, _)) => rigid_clash binders hs ht
                       | (Bound i, Bound j) =>
                         (if not ((i : IntInf.int) = j)
                           then raisea (Unif (Clash_BB (binders, i, j)))
                           else bindM (zip_eq ss ts)
                                  (fn ps =>
                                    foldM (fn (a, b) => unif alg binders a b) ps
                                      env))
                       | (Bound _, Abs (_, _, _)) => rigid_clash binders hs ht
                       | (Bound _, _ $ _) => rigid_clash binders hs ht
                       | (Abs (_, _, _), _) => rigid_clash binders hs ht
                       | (_ $ _, _) => rigid_clash binders hs ht)))))
                               end)))));

fun loose_bvar (Bound i) k = IntInf.<= (k, i)
  | loose_bvar (f $ t) k = loose_bvar f k orelse loose_bvar t k
  | loose_bvar (Abs (uu, uv, t)) k =
    loose_bvar t (IntInf.+ (k, (1 : IntInf.int)))
  | loose_bvar (Const (v, va)) ux = false
  | loose_bvar (Free (v, va)) ux = false
  | loose_bvar (Var (v, va)) ux = false;

fun is_open t = loose_bvar t (0 : IntInf.int);

fun fastype_of_bound (t :: ts) i =
  (if ((i : IntInf.int) = (0 : IntInf.int)) then return t
    else fastype_of_bound ts (IntInf.- (i, (1 : IntInf.int))))
  | fastype_of_bound [] i =
    raisea (Term_Error ("fastype_of: Bound", [Bound i]));

fun fastype_of_atom uu (Const (uv, t)) = return t
  | fastype_of_atom uw (Free (ux, t)) = return t
  | fastype_of_atom uy (Var (uz, t)) = return t
  | fastype_of_atom ts (Bound i) = fastype_of_bound ts i
  | fastype_of_atom va (Abs (v, vc, vd)) = raisea (Failure "fastype_of_atom")
  | fastype_of_atom va (v $ vc) = raisea (Failure "fastype_of_atom");

fun range_type_ofT ta (Type (n, [t, u])) =
  (if ((n : string) = "fun") then return u
    else raisea (Term_Error ("fastype_of: expected function type", [ta])))
  | range_type_ofT t (Type (v, [])) =
    raisea (Term_Error ("fastype_of: expected function type", [t]))
  | range_type_ofT t (Type (v, [vb])) =
    raisea (Term_Error ("fastype_of: expected function type", [t]))
  | range_type_ofT t (Type (v, vb :: vd :: vf :: vg)) =
    raisea (Term_Error ("fastype_of: expected function type", [t]))
  | range_type_ofT t (TFree (v, va)) =
    raisea (Term_Error ("fastype_of: expected function type", [t]))
  | range_type_ofT t (TVar (v, va)) =
    raisea (Term_Error ("fastype_of: expected function type", [t]));

fun fastype_of_term ts (Abs (uu, ta, t)) =
  bindM (fastype_of_term (ta :: ts) t) (fn u => return (Type ("fun", [ta, u])))
  | fastype_of_term ts (t $ uv) = range_type_of ts t
  | fastype_of_term ts (Const (v, va)) = fastype_of_atom ts (Const (v, va))
  | fastype_of_term ts (Free (v, va)) = fastype_of_atom ts (Free (v, va))
  | fastype_of_term ts (Var (v, va)) = fastype_of_atom ts (Var (v, va))
  | fastype_of_term ts (Bound v) = fastype_of_atom ts (Bound v)
and range_type_of ts (Abs (uw, t, u)) = fastype_of_term (t :: ts) u
  | range_type_of ts (t $ u) =
    bindM (range_type_of ts t) (range_type_ofT (t $ u))
  | range_type_of ts (Const (v, va)) =
    bindM (fastype_of_atom ts (Const (v, va))) (range_type_ofT (Const (v, va)))
  | range_type_of ts (Free (v, va)) =
    bindM (fastype_of_atom ts (Free (v, va))) (range_type_ofT (Free (v, va)))
  | range_type_of ts (Var (v, va)) =
    bindM (fastype_of_atom ts (Var (v, va))) (range_type_ofT (Var (v, va)))
  | range_type_of ts (Bound v) =
    bindM (fastype_of_atom ts (Bound v)) (range_type_ofT (Bound v));

fun fastype_of t = fastype_of_term [] t;

fun fo_mtch alg inAbs instsp pat obj =
  let
    val (tyinsts, insts) = instsp;
  in
    (if is_Var pat
      then (case pat of Const (_, _) => raisea (Failure "fo_mtch")
             | Free (_, _) => raisea (Failure "fo_mtch")
             | Var (ixn, t) =>
               (if inAbs andalso is_open obj then raisea Match
                 else bindM (lookup1 insts ixn t)
                        (fn a =>
                          (case a
                            of NONE =>
                              bindM (fastype_of obj)
                                (fn tT =>
                                  bindM (typ_match_m alg t tT tyinsts)
                                    (fn tyinstsa =>
                                      bindM (update_new (ixn, (t, obj)) insts)
(fn instsa => return (tyinstsa, instsa))))
                            | SOME u =>
                              (if aeconv obj u then return instsp
                                else raisea Match))))
             | Bound _ => raisea (Failure "fo_mtch")
             | Abs (_, _, _) => raisea (Failure "fo_mtch")
             | _ $ _ => raisea (Failure "fo_mtch"))
      else (case (pat, obj)
             of (Const (a, t), ba) =>
               (case ba
                 of Const (b, u) =>
                   (if ((a : string) = b)
                     then bindM (typ_match_m alg t u tyinsts)
                            (fn tyinstsa => return (tyinstsa, insts))
                     else raisea Match)
                 | Free (_, _) => raisea Match | Var (_, _) => raisea Match
                 | Bound _ => raisea Match
                 | Abs (_, _, aa) =>
                   fo_mtch alg true instsp (incr pat $ Bound (0 : IntInf.int))
                     aa
                 | _ $ _ => raisea Match)
             | (Free (a, t), ba) =>
               (case ba of Const (_, _) => raisea Match
                 | Free (b, u) =>
                   (if ((a : string) = b)
                     then bindM (typ_match_m alg t u tyinsts)
                            (fn tyinstsa => return (tyinstsa, insts))
                     else raisea Match)
                 | Var (_, _) => raisea Match | Bound _ => raisea Match
                 | Abs (_, _, aa) =>
                   fo_mtch alg true instsp (incr pat $ Bound (0 : IntInf.int))
                     aa
                 | _ $ _ => raisea Match)
             | (Var (_, _), Const (_, _)) => raisea Match
             | (Var (_, _), Free (_, _)) => raisea Match
             | (Var (_, _), Var (_, _)) => raisea Match
             | (Var (_, _), Bound _) => raisea Match
             | (Var (_, _), Abs (_, _, a)) =>
               fo_mtch alg true instsp (incr pat $ Bound (0 : IntInf.int)) a
             | (Var (_, _), _ $ _) => raisea Match
             | (Bound _, Const (_, _)) => raisea Match
             | (Bound _, Free (_, _)) => raisea Match
             | (Bound _, Var (_, _)) => raisea Match
             | (Bound i, Bound j) =>
               (if ((i : IntInf.int) = j) then return instsp else raisea Match)
             | (Bound _, Abs (_, _, a)) =>
               fo_mtch alg true instsp (incr pat $ Bound (0 : IntInf.int)) a
             | (Bound _, _ $ _) => raisea Match
             | (Abs (_, _, _), Const (_, _)) => raisea Match
             | (Abs (_, _, _), Free (_, _)) => raisea Match
             | (Abs (_, _, _), Var (_, _)) => raisea Match
             | (Abs (_, _, _), Bound _) => raisea Match
             | (Abs (_, t, ta), Abs (_, u, ua)) =>
               bindM (typ_match_m alg t u tyinsts)
                 (fn tyinstsa => fo_mtch alg true (tyinstsa, insts) ta ua)
             | (Abs (_, _, _), _ $ _) => raisea Match
             | (_ $ _, Const (_, _)) => raisea Match
             | (_ $ _, Free (_, _)) => raisea Match
             | (_ $ _, Var (_, _)) => raisea Match
             | (_ $ _, Bound _) => raisea Match
             | (_ $ _, Abs (_, _, a)) =>
               fo_mtch alg true instsp (incr pat $ Bound (0 : IntInf.int)) a
             | (f $ t, g $ u) =>
               bindM (fo_mtch alg inAbs instsp f g)
                 (fn instspa => fo_mtch alg inAbs instspa t u)))
  end;

fun first_order_match alg pat obj env = fo_mtch alg false env pat obj;

fun match alg pat obj envir =
  bindM (fastype_of pat)
    (fn pT =>
      bindM (fastype_of obj)
        (fn oT =>
          bindM (typ_match_m alg pT oT (fst envir))
            (fn iTs =>
              let
                val envira = (iTs, snd envir);
              in
                handlea (mtch alg [] pat obj envira)
                  (fn e =>
                    (case e of Unif _ => raisea e
                      | Pattern => first_order_match alg pat obj envira
                      | Match => raisea e | TUnify => raisea e
                      | Type_Match => raisea e | Class_Error _ => raisea e
                      | Type_Error (_, _, _) => raisea e
                      | Term_Error (_, _) => raisea e | Failure _ => raisea e
                      | Subscript => raisea e | Unequal_Lengths => raisea e
                      | Dup _ => raisea e))
              end)));

fun unify alg s t env = unif alg [] s t env;

fun is_Bound (Bound uu) = true
  | is_Bound (Const (v, va)) = false
  | is_Bound (Free (v, va)) = false
  | is_Bound (Var (v, va)) = false
  | is_Bound (Abs (v, va, vb)) = false
  | is_Bound (v $ va) = false;

fun has_duplicates_by eq [] = false
  | has_duplicates_by eq (x :: xs) =
    list_ex (eq x) xs orelse has_duplicates_by eq xs;

fun pattern t =
  (case t
    of Const (_, _) =>
      let
        val (head, args) = strip_comb t;
      in
        (if is_Var head
          then list_all is_Bound args andalso
                 not (has_duplicates_by aconv_term args)
          else list_all pattern args)
      end
    | Free (_, _) =>
      let
        val (head, args) = strip_comb t;
      in
        (if is_Var head
          then list_all is_Bound args andalso
                 not (has_duplicates_by aconv_term args)
          else list_all pattern args)
      end
    | Var (_, _) =>
      let
        val (head, args) = strip_comb t;
      in
        (if is_Var head
          then list_all is_Bound args andalso
                 not (has_duplicates_by aconv_term args)
          else list_all pattern args)
      end
    | Bound _ =>
      let
        val (head, args) = strip_comb t;
      in
        (if is_Var head
          then list_all is_Bound args andalso
                 not (has_duplicates_by aconv_term args)
          else list_all pattern args)
      end
    | Abs (_, _, a) => pattern a
    | _ $ _ =>
      let
        val (head, args) = strip_comb t;
      in
        (if is_Var head
          then list_all is_Bound args andalso
                 not (has_duplicates_by aconv_term args)
          else list_all pattern args)
      end);

end; (*struct Pattern_Generated*)


